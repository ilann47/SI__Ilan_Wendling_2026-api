    endereco       VARCHAR(120),
    numero         VARCHAR(10),
    complemento    VARCHAR(100),
    bairro         VARCHAR(60),
    cep            VARCHAR(9),
    cidade_id             BIGINT,
    nacionalidade_id      BIGINT,                   -- FK pais
    condicao_pagamento_id BIGINT,
    limite_credito        NUMERIC(15,2) NOT NULL DEFAULT 0,
