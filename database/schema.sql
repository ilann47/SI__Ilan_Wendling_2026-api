-- =====================================================================
-- VEICULO  (pertence a um cliente quando mensalista; avulso = cliente_id nulo)
-- =====================================================================
CREATE TABLE veiculo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa       VARCHAR(10)   NOT NULL,
    modelo      VARCHAR(60),
    cor         VARCHAR(30),
    tipo        VARCHAR(20)   NOT NULL DEFAULT 'CARRO',
    cliente_id  BIGINT,
    observacao  VARCHAR(255),
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_veiculo_placa   UNIQUE (placa),
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE RESTRICT,
    CONSTRAINT ck_veiculo_tipo    CHECK (tipo IN ('CARRO','MOTO'))
);
CREATE INDEX ix_veiculo_cliente ON veiculo (cliente_id);

-- =====================================================================
-- TARIFA  (precos vigentes num so lugar)
-- =====================================================================
CREATE TABLE tarifa (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao          VARCHAR(80)    NOT NULL,
    valor_hora         NUMERIC(10,2)  NOT NULL,   -- valor por hora cheia/fracao
    valor_diaria       NUMERIC(10,2)  NOT NULL,   -- teto: avulso nunca paga mais que isso por dia
    tolerancia_min     INTEGER        NOT NULL DEFAULT 15,  -- cortesia: abaixo disso, gratis
    valor_mensalidade  NUMERIC(10,2)  NOT NULL,   -- valor padrao do plano mensalista
    ativo              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_tarifa_valores CHECK (
        valor_hora >= 0 AND valor_diaria >= 0 AND valor_mensalidade >= 0 AND tolerancia_min >= 0
    )
);

-- =====================================================================
-- MENSALISTA  (o contrato: liga cliente + veiculo)
-- =====================================================================
CREATE TABLE mensalista (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    BIGINT         NOT NULL,
    veiculo_id    BIGINT         NOT NULL,
    valor_mensal  NUMERIC(10,2)  NOT NULL,
    data_inicio   DATE           NOT NULL DEFAULT CURRENT_DATE,
    data_fim      DATE,                              -- nulo = vigente
    status        VARCHAR(20)    NOT NULL DEFAULT 'ATIVO',
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_mensalista_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mensalista_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo (id) ON DELETE RESTRICT,
    CONSTRAINT ck_mensalista_status  CHECK (status IN ('ATIVO','SUSPENSO','CANCELADO')),
    CONSTRAINT ck_mensalista_periodo CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);
CREATE INDEX ix_mensalista_cliente ON mensalista (cliente_id);
CREATE INDEX ix_mensalista_veiculo ON mensalista (veiculo_id);
-- Regra de negocio: no maximo 1 contrato ATIVO por veiculo
CREATE UNIQUE INDEX uq_mensalista_veiculo_ativo ON mensalista (veiculo_id) WHERE status = 'ATIVO';

-- =====================================================================
-- MOVIMENTACAO  (o ticket de patio: entrada/saida)
-- =====================================================================
CREATE TABLE movimentacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id     BIGINT         NOT NULL,
    mensalista_id  BIGINT,                           -- preenchido quando tipo = MENSALISTA
    tarifa_id      BIGINT,                           -- tarifa aplicada (avulso); nulo p/ mensalista
    tipo           VARCHAR(20)    NOT NULL,
    data_entrada   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    data_saida     TIMESTAMPTZ,                      -- nulo = ainda no patio (evento horario; != nota_saida.data_saida que e DATE)
    valor_cobrado  NUMERIC(10,2),                    -- preenchido na saida
    status         VARCHAR(20)    NOT NULL DEFAULT 'ABERTO',
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_mov_veiculo    FOREIGN KEY (veiculo_id)    REFERENCES veiculo (id)    ON DELETE RESTRICT,
    CONSTRAINT fk_mov_mensalista FOREIGN KEY (mensalista_id) REFERENCES mensalista (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mov_tarifa     FOREIGN KEY (tarifa_id)     REFERENCES tarifa (id)     ON DELETE RESTRICT,
    CONSTRAINT ck_mov_tipo   CHECK (tipo   IN ('AVULSO','MENSALISTA')),
    CONSTRAINT ck_mov_status CHECK (status IN ('ABERTO','FECHADO','CANCELADO')),
    CONSTRAINT ck_mov_saida  CHECK (data_saida IS NULL OR data_saida >= data_entrada),
    -- Coerencia: mensalista informa o contrato; avulso nao
    CONSTRAINT ck_mov_tipo_coerencia CHECK (
        (tipo = 'MENSALISTA' AND mensalista_id IS NOT NULL) OR
        (tipo = 'AVULSO'     AND mensalista_id IS NULL)
    )
);
CREATE INDEX ix_mov_veiculo      ON movimentacao (veiculo_id);
CREATE INDEX ix_mov_mensalista   ON movimentacao (mensalista_id);
CREATE INDEX ix_mov_data_entrada ON movimentacao (data_entrada);
-- Regra de negocio: no maximo 1 movimentacao ABERTA por veiculo (nao entra 2x)
CREATE UNIQUE INDEX uq_mov_veiculo_aberta ON movimentacao (veiculo_id) WHERE status = 'ABERTO';

