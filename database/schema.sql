-- =====================================================================
-- Estacionamento Kaneko - Schema do banco (controle basico, v1)
-- PostgreSQL 17 - banco: estacionamento_kaneko
-- SQL "tradicional" (DDL puro). Este conteudo vira a migration
-- Flyway V1 quando comecarmos a codar.
-- Escopo: mensalista + avulso (hora/diaria) + Geografia + Pagamento (forma/
--         condicao/parcela) + RH (cargo/funcionario) + Fornecedor + Modulo
--         Conveniencia/Comercial (em construcao, por partes). Sem multifilial.
-- Base: PDF modelo (pratica profissional) + projeto aprovado do amigo (PizzariaGraff).
-- =====================================================================

-- =====================================================================
-- PAIS
-- =====================================================================
CREATE TABLE pais (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(60)   NOT NULL,
    sigla         VARCHAR(3),                       -- ISO (ex.: BRA)
    codigo        VARCHAR(5),                       -- codigo do pais
    nacionalidade VARCHAR(100),                     -- gentilico (ex.: Brasileiro)
    moeda         VARCHAR(30),                      -- [V2] moeda corrente (nome ou codigo ISO 4217)
    ddi           VARCHAR(5),                       -- [V2] codigo de discagem internacional (ex.: 55)
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_pais_nome UNIQUE (nome)
);

-- =====================================================================
-- ESTADO
-- =====================================================================
CREATE TABLE estado (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(60)   NOT NULL,
    uf          VARCHAR(3)    NOT NULL,           -- sigla (ex.: PR, SP)
    pais_id     BIGINT        NOT NULL,
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_estado_pais   FOREIGN KEY (pais_id) REFERENCES pais (id) ON DELETE RESTRICT,
    CONSTRAINT uq_estado_uf_pais UNIQUE (pais_id, uf)
);
CREATE INDEX ix_estado_pais ON estado (pais_id);

-- =====================================================================
-- CIDADE
-- =====================================================================
CREATE TABLE cidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(80)   NOT NULL,
    ddd         VARCHAR(4),
    codigo_ibge VARCHAR(10),
    estado_id   BIGINT        NOT NULL,
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_cidade_estado    FOREIGN KEY (estado_id) REFERENCES estado (id) ON DELETE RESTRICT,
    CONSTRAINT uq_cidade_nome_estado UNIQUE (estado_id, nome)
);
CREATE INDEX ix_cidade_estado ON cidade (estado_id);

-- =====================================================================
-- CARGO  (funcao do funcionario)
-- =====================================================================
CREATE TABLE cargo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100)  NOT NULL,
    descricao     VARCHAR(255),
    salario_base  NUMERIC(10,2) NOT NULL DEFAULT 0,
    carga_horaria NUMERIC(6,2),                     -- horas mensais
    requer_cnh    BOOLEAN       NOT NULL DEFAULT FALSE,
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_cargo_nome UNIQUE (nome),
    CONSTRAINT ck_cargo_valores CHECK (salario_base >= 0 AND (carga_horaria IS NULL OR carga_horaria >= 0))
);

-- =====================================================================
-- FUNCIONARIO
-- =====================================================================
CREATE TABLE funcionario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120)  NOT NULL,
    apelido               VARCHAR(60),
    tipo                  VARCHAR(20)   NOT NULL DEFAULT 'FISICA',  -- FISICA / JURIDICA
    cpf                   VARCHAR(20)   NOT NULL,
    rg_inscricao_estadual VARCHAR(20),
    data_nascimento       DATE,
    sexo                  VARCHAR(20),                  -- MASCULINO / FEMININO / OUTRO
    estado_civil          VARCHAR(20),                  -- SOLTEIRO / CASADO / ...
    telefone              VARCHAR(20),
    email                 VARCHAR(120),
    endereco              VARCHAR(120),
    numero                VARCHAR(10),
    complemento           VARCHAR(100),
    bairro                VARCHAR(60),
    cep                   VARCHAR(9),
    cidade_id             BIGINT,
    nacionalidade_id      BIGINT,                       -- FK pais
    cargo_id              BIGINT        NOT NULL,
    cnh                   VARCHAR(20),
    data_validade_cnh     DATE,
    data_admissao         DATE          NOT NULL DEFAULT CURRENT_DATE,
    data_demissao         DATE,
    salario               NUMERIC(10,2),
    observacao            VARCHAR(255),
    ativo                 BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_funcionario_cidade        FOREIGN KEY (cidade_id)        REFERENCES cidade (id) ON DELETE RESTRICT,
    CONSTRAINT fk_funcionario_cargo         FOREIGN KEY (cargo_id)         REFERENCES cargo (id)  ON DELETE RESTRICT,
    CONSTRAINT fk_funcionario_nacionalidade FOREIGN KEY (nacionalidade_id) REFERENCES pais (id)   ON DELETE RESTRICT,
    CONSTRAINT uq_funcionario_cpf      UNIQUE (cpf),
    CONSTRAINT ck_funcionario_salario  CHECK (salario IS NULL OR salario >= 0),
    CONSTRAINT ck_funcionario_tipo     CHECK (tipo IN ('FISICA','JURIDICA')),
    CONSTRAINT ck_funcionario_sexo     CHECK (sexo IS NULL OR sexo IN ('MASCULINO','FEMININO','OUTRO')),
    CONSTRAINT ck_funcionario_civil    CHECK (estado_civil IS NULL OR estado_civil IN ('SOLTEIRO','CASADO','SEPARADO','DIVORCIADO','VIUVO','OUTRO'))
);
CREATE INDEX ix_funcionario_cidade        ON funcionario (cidade_id);
CREATE INDEX ix_funcionario_cargo         ON funcionario (cargo_id);
CREATE INDEX ix_funcionario_nacionalidade ON funcionario (nacionalidade_id);

-- =====================================================================
-- FORMA_PAGAMENTO
-- =====================================================================
CREATE TABLE forma_pagamento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100)  NOT NULL,            -- Dinheiro, Cartao, Pix, Boleto
    descricao   VARCHAR(255)  NOT NULL,
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_forma_pagamento_nome UNIQUE (nome)
);

-- =====================================================================
-- CONDICAO_PAGAMENTO  (alinhada ao projeto aprovado: parcelas + juros/multa/desconto)
-- =====================================================================
CREATE TABLE condicao_pagamento (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(100)   NOT NULL,   -- A vista, 30 dias, 30/60/90
    numero_parcelas       INTEGER        NOT NULL DEFAULT 1,
    percentual_juros      NUMERIC(6,2)   NOT NULL DEFAULT 0,
    percentual_multa      NUMERIC(6,2)   NOT NULL DEFAULT 0,
    percentual_desconto   NUMERIC(5,2)   NOT NULL DEFAULT 0,
    ativo                 BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_condicao_pagamento_nome UNIQUE (nome),
    CONSTRAINT ck_condicao_parcelas    CHECK (numero_parcelas >= 1),
    CONSTRAINT ck_condicao_percentuais CHECK (percentual_juros >= 0 AND percentual_multa >= 0 AND percentual_desconto >= 0 AND percentual_desconto <= 100)
);

-- =====================================================================
-- PARCELA_CONDICAO_PAGAMENTO  (detalhe das parcelas de uma condicao)
-- =====================================================================
CREATE TABLE parcela_condicao_pagamento (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condicao_pagamento_id  BIGINT         NOT NULL,
    numero                 INTEGER        NOT NULL,   -- sequencial da parcela (1, 2, 3...)
    dias                   INTEGER        NOT NULL,   -- dias p/ vencimento a partir da emissao
    percentual             NUMERIC(5,2)   NOT NULL,   -- % do valor total nesta parcela
    forma_pagamento_id     BIGINT,                    -- forma especifica desta parcela (opcional)
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_parcela_condicao FOREIGN KEY (condicao_pagamento_id) REFERENCES condicao_pagamento (id) ON DELETE CASCADE,
    CONSTRAINT fk_parcela_forma    FOREIGN KEY (forma_pagamento_id)    REFERENCES forma_pagamento (id)    ON DELETE SET NULL,
    CONSTRAINT uq_parcela_condicao_numero UNIQUE (condicao_pagamento_id, numero),
    CONSTRAINT ck_parcela_valores  CHECK (numero >= 1 AND dias >= 0 AND percentual >= 0 AND percentual <= 100)
);
CREATE INDEX ix_parcela_condicao ON parcela_condicao_pagamento (condicao_pagamento_id);
CREATE INDEX ix_parcela_forma    ON parcela_condicao_pagamento (forma_pagamento_id);

-- =====================================================================
-- FORNECEDOR
-- =====================================================================
