    ON conta_receber(organizacao_id, venda_administrativa_id)
    WHERE venda_administrativa_id IS NOT NULL;

CREATE FUNCTION impedir_owner_venda_administrativa_v64() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NEW.organizacao_id IS DISTINCT FROM OLD.organizacao_id THEN
        RAISE EXCEPTION 'owner da venda e imutavel [ck_venda_administrativa_owner_imutavel]'
            USING ERRCODE='23514', CONSTRAINT='ck_venda_administrativa_owner_imutavel';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_00_venda_administrativa_owner
BEFORE UPDATE OF organizacao_id ON venda_administrativa
FOR EACH ROW EXECUTE FUNCTION impedir_owner_venda_administrativa_v64();

CREATE FUNCTION validar_nota_venda_administrativa_v64() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE owner_ref BIGINT; cliente_ref BIGINT; local_ref BIGINT; status_ref VARCHAR(20);
BEGIN
    IF NEW.venda_administrativa_id IS NULL THEN RETURN NEW; END IF;
    SELECT organizacao_id, cliente_id, local_estoque_id, status
      INTO owner_ref, cliente_ref, local_ref, status_ref
      FROM venda_administrativa WHERE id=NEW.venda_administrativa_id;
    IF NOT FOUND OR owner_ref IS DISTINCT FROM NEW.organizacao_id THEN
        RAISE EXCEPTION 'owner da nota diverge da venda [fk_nota_saida_venda_tenant]'
            USING ERRCODE='23503', CONSTRAINT='fk_nota_saida_venda_tenant';
    END IF;
    IF cliente_ref IS DISTINCT FROM NEW.cliente_id THEN
        RAISE EXCEPTION 'cliente da nota diverge da venda [ck_nota_venda_cliente]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_venda_cliente';
    END IF;
    IF local_ref IS DISTINCT FROM NEW.local_estoque_id THEN
        RAISE EXCEPTION 'local da nota diverge da venda [ck_nota_venda_local]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_venda_local';
    END IF;
    IF status_ref <> 'CONFIRMADA' THEN
        RAISE EXCEPTION 'venda precisa estar confirmada [ck_nota_venda_confirmada]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_venda_confirmada';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_nota_venda_administrativa_v64
BEFORE INSERT OR UPDATE OF organizacao_id, venda_administrativa_id, cliente_id,
    local_estoque_id ON nota_saida
FOR EACH ROW EXECUTE FUNCTION validar_nota_venda_administrativa_v64();

