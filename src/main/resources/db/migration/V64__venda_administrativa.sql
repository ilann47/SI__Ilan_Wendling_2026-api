CREATE TABLE venda_administrativa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    condicao_pagamento_id BIGINT,
    local_estoque_id BIGINT NOT NULL,
    numero VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_emissao DATE NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    subtotal NUMERIC(15,2) NOT NULL,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL,
    observacao VARCHAR(500),
    motivo_cancelamento VARCHAR(300),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_venda_administrativa_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_venda_administrativa_cliente_tenant FOREIGN KEY (organizacao_id, cliente_id)
        REFERENCES cliente(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_venda_administrativa_condicao_tenant
        FOREIGN KEY (organizacao_id, condicao_pagamento_id)
        REFERENCES condicao_pagamento(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_venda_administrativa_local_tenant
        FOREIGN KEY (local_estoque_id, organizacao_id)
        REFERENCES local_estoque(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_venda_administrativa_organizacao_id UNIQUE (organizacao_id, id),
    CONSTRAINT uq_venda_administrativa_numero UNIQUE (organizacao_id, numero),
    CONSTRAINT ck_venda_administrativa_status CHECK
        (status IN ('RASCUNHO','CONFIRMADA','CANCELADA')),
    CONSTRAINT ck_venda_administrativa_moeda CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_venda_administrativa_valores CHECK (
        subtotal >= 0 AND valor_desconto >= 0 AND valor_desconto <= subtotal
        AND valor_total = subtotal - valor_desconto),
    CONSTRAINT ck_venda_administrativa_cancelamento CHECK (
        (status='CANCELADA' AND motivo_cancelamento IS NOT NULL
            AND length(btrim(motivo_cancelamento)) BETWEEN 1 AND 300)
        OR (status<>'CANCELADA' AND motivo_cancelamento IS NULL)),
    CONSTRAINT ck_venda_administrativa_version CHECK (version >= 0)
);

CREATE TABLE item_venda_administrativa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    venda_administrativa_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    sequencia INTEGER NOT NULL,
    quantidade NUMERIC(15,3) NOT NULL,
    valor_unitario NUMERIC(15,2) NOT NULL,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_venda_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_venda_venda_tenant FOREIGN KEY
        (organizacao_id, venda_administrativa_id)
        REFERENCES venda_administrativa(organizacao_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_item_venda_produto_tenant FOREIGN KEY (organizacao_id, produto_id)
        REFERENCES produto(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_item_venda_sequencia UNIQUE (venda_administrativa_id, sequencia),
    CONSTRAINT uq_item_venda_produto UNIQUE (venda_administrativa_id, produto_id),
    CONSTRAINT ck_item_venda_sequencia CHECK (sequencia > 0),
    CONSTRAINT ck_item_venda_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_venda_valores CHECK (
        valor_unitario >= 0 AND valor_desconto >= 0
        AND valor_desconto <= quantidade * valor_unitario
        AND valor_total = quantidade * valor_unitario - valor_desconto)
);

