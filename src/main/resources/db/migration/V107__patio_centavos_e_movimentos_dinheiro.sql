-- Exclusivamente NOVAS estadias recebem marcador. Não atualizar documentos nem valores anteriores.
CREATE TABLE patio_cobranca_centavos (
    organizacao_id BIGINT NOT NULL,
    movimentacao_id BIGINT NOT NULL,
    fase VARCHAR(7) NOT NULL CHECK(fase IN ('ENTRADA','SAIDA')),
    valor_calculado_micros NUMERIC(24,0),
    valor_devido_micros NUMERIC(24,0),
    diferenca_micros NUMERIC(24,0),
    confirmado_em TIMESTAMPTZ,
    PRIMARY KEY(organizacao_id,movimentacao_id),
    FOREIGN KEY(organizacao_id,movimentacao_id) REFERENCES movimentacao(organizacao_id,id),
    CHECK((valor_calculado_micros IS NULL AND valor_devido_micros IS NULL AND diferenca_micros IS NULL AND confirmado_em IS NULL)
       OR (valor_calculado_micros IS NOT NULL AND valor_devido_micros IS NOT NULL AND diferenca_micros IS NOT NULL
           AND valor_calculado_micros>=0 AND valor_devido_micros>=0
           AND mod(valor_devido_micros,10000)=0
           AND diferenca_micros=valor_devido_micros-valor_calculado_micros))
);
ALTER TABLE patio_checkout ADD COLUMN valor_calculado_micros NUMERIC(24,0);

CREATE TABLE patio_movimento_dinheiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    turno_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    chave UUID NOT NULL,
    tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('SUPRIMENTO','SANGRIA')),
    valor_micros NUMERIC(24,0) NOT NULL CHECK(valor_micros>0),
    motivo VARCHAR(300) NOT NULL CHECK(length(trim(motivo)) BETWEEN 10 AND 300),
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(organizacao_id,chave),
    FOREIGN KEY(organizacao_id,turno_id) REFERENCES patio_turno(organizacao_id,id)
);
CREATE INDEX ix_patio_movimento_dinheiro_turno ON patio_movimento_dinheiro(organizacao_id,turno_id,id);
CREATE FUNCTION proteger_movimento_dinheiro_patio() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Movimentos de dinheiro do caixa são imutáveis.';
END;
$$;
CREATE TRIGGER tr_patio_dinheiro_imutavel BEFORE UPDATE OR DELETE ON patio_movimento_dinheiro
FOR EACH ROW EXECUTE FUNCTION proteger_movimento_dinheiro_patio();
CREATE FUNCTION proteger_snapshot_centavos_patio() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' OR OLD.confirmado_em IS NOT NULL THEN
    RAISE EXCEPTION 'Snapshot de cobrança confirmado não pode ser alterado.';
  END IF;
  IF NEW.organizacao_id<>OLD.organizacao_id OR NEW.movimentacao_id<>OLD.movimentacao_id OR NEW.fase<>OLD.fase THEN
    RAISE EXCEPTION 'A origem do snapshot não pode ser alterada.';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER tr_patio_centavos_imutavel BEFORE UPDATE OR DELETE ON patio_cobranca_centavos
FOR EACH ROW EXECUTE FUNCTION proteger_snapshot_centavos_patio();
