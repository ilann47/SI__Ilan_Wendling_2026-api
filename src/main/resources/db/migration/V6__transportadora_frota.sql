-- Logistica de abastecimento (modelo do projeto aprovado): transportadora que
-- faz o frete das compras, sua frota de veiculos (N:N) e o vinculo do
-- fornecedor com a transportadora padrao.

CREATE TABLE transportadora (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(150)  NOT NULL,          -- razao social
    nome_fantasia         VARCHAR(120),
    tipo                  VARCHAR(20)   NOT NULL DEFAULT 'JURIDICA',  -- FISICA / JURIDICA
    documento             VARCHAR(20)   NOT NULL,          -- CNPJ/CPF
    rg_inscricao_estadual VARCHAR(20),
    telefone              VARCHAR(20),
    email                 VARCHAR(120),
    endereco              VARCHAR(120),
    numero                VARCHAR(10),
    complemento           VARCHAR(100),
    bairro                VARCHAR(60),
    cep                   VARCHAR(9),
    cidade_id             BIGINT,
    condicao_pagamento_id BIGINT,
    observacao            VARCHAR(255),
    ativo                 BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_transportadora_documento UNIQUE (documento),
    CONSTRAINT fk_transportadora_cidade   FOREIGN KEY (cidade_id)             REFERENCES cidade (id)             ON DELETE RESTRICT,
    CONSTRAINT fk_transportadora_condicao FOREIGN KEY (condicao_pagamento_id) REFERENCES condicao_pagamento (id) ON DELETE RESTRICT,
    CONSTRAINT ck_transportadora_tipo     CHECK (tipo IN ('FISICA','JURIDICA'))
);
CREATE INDEX ix_transportadora_cidade   ON transportadora (cidade_id);
CREATE INDEX ix_transportadora_condicao ON transportadora (condicao_pagamento_id);

CREATE TABLE veiculo_frota (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa       VARCHAR(10)   NOT NULL,
    modelo      VARCHAR(50),
    marca       VARCHAR(50),
    ano         INTEGER,
    capacidade  NUMERIC(10,2),                             -- capacidade de carga
    observacao  VARCHAR(255),
    ativo       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_veiculo_frota_placa      UNIQUE (placa),
    CONSTRAINT ck_veiculo_frota_ano        CHECK (ano IS NULL OR ano >= 1900),
    CONSTRAINT ck_veiculo_frota_capacidade CHECK (capacidade IS NULL OR capacidade >= 0)
);

-- N:N transportadora x veiculo de frota (a frota da transportadora)
CREATE TABLE transportadora_veiculo_frota (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transportadora_id BIGINT        NOT NULL,
    veiculo_frota_id  BIGINT        NOT NULL,
    ativo             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_transp_veiculo_frota UNIQUE (transportadora_id, veiculo_frota_id),
    CONSTRAINT fk_tvf_transportadora   FOREIGN KEY (transportadora_id) REFERENCES transportadora (id) ON DELETE CASCADE,
    CONSTRAINT fk_tvf_veiculo          FOREIGN KEY (veiculo_frota_id)  REFERENCES veiculo_frota (id)  ON DELETE RESTRICT
);
CREATE INDEX ix_tvf_transportadora ON transportadora_veiculo_frota (transportadora_id);
CREATE INDEX ix_tvf_veiculo        ON transportadora_veiculo_frota (veiculo_frota_id);

-- fornecedor aponta para a transportadora padrao do frete
ALTER TABLE fornecedor ADD COLUMN transportadora_id BIGINT;
ALTER TABLE fornecedor ADD CONSTRAINT fk_fornecedor_transportadora
    FOREIGN KEY (transportadora_id) REFERENCES transportadora (id) ON DELETE RESTRICT;
CREATE INDEX ix_fornecedor_transportadora ON fornecedor (transportadora_id);
