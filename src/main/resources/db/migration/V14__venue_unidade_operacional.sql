CREATE TABLE unidade_operacional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    nome VARCHAR(160) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    endereco VARCHAR(120) NOT NULL,
    numero VARCHAR(10),
    complemento VARCHAR(100),
    bairro VARCHAR(60) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    cidade_id BIGINT NOT NULL REFERENCES cidade(id) ON DELETE RESTRICT,
    fuso_horario VARCHAR(60) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_unidade_operacional_tipo CHECK (tipo = 'VENUE'),
    CONSTRAINT ck_unidade_operacional_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_unidade_operacional_nome_normalizado
    ON unidade_operacional (organizacao_id, lower(btrim(nome)));
CREATE INDEX ix_unidade_operacional_organizacao_ativo
    ON unidade_operacional (organizacao_id, ativo);
CREATE INDEX ix_unidade_operacional_cidade
    ON unidade_operacional (cidade_id);
