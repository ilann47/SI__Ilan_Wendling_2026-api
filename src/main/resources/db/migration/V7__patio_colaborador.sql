-- Subsistema multi-patio (operacao SaaS do app): o Patio (estabelecimento /
-- filial de estacionamento), sua equipe de Colaboradores (com fluxo de convite)
-- e o vinculo da movimentacao ao patio onde ocorreu — base da ocupacao por patio
-- exibida na tela inicial do aplicativo.

CREATE TABLE patio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120)  NOT NULL,
    endereco         VARCHAR(120),
    numero           VARCHAR(10),
    complemento      VARCHAR(100),
    bairro           VARCHAR(60),
    cep              VARCHAR(9),
    cidade_id        BIGINT,
    capacidade_vagas INTEGER       NOT NULL,        -- total de vagas do patio
    observacao       VARCHAR(255),
    ativo            BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_patio_cidade     FOREIGN KEY (cidade_id) REFERENCES cidade (id) ON DELETE RESTRICT,
    CONSTRAINT ck_patio_capacidade CHECK (capacidade_vagas > 0)
);
CREATE INDEX ix_patio_cidade ON patio (cidade_id);

CREATE TABLE colaborador (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patio_id   BIGINT        NOT NULL,
    nome       VARCHAR(120)  NOT NULL,
    email      VARCHAR(120)  NOT NULL,
    perfil     VARCHAR(20)   NOT NULL DEFAULT 'OPERADOR',   -- ADMIN / OPERADOR
    status     VARCHAR(20)   NOT NULL DEFAULT 'CONVIDADO',  -- CONVIDADO / ATIVO / INATIVO
    ativo      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_colaborador_patio       FOREIGN KEY (patio_id) REFERENCES patio (id) ON DELETE CASCADE,
    CONSTRAINT uq_colaborador_patio_email UNIQUE (patio_id, email),
    CONSTRAINT ck_colaborador_perfil      CHECK (perfil IN ('ADMIN','OPERADOR')),
    CONSTRAINT ck_colaborador_status      CHECK (status IN ('CONVIDADO','ATIVO','INATIVO'))
);
CREATE INDEX ix_colaborador_patio ON colaborador (patio_id);

-- a movimentacao passa a referenciar o patio onde ocorreu (opcional para nao
-- afetar dados existentes); a ocupacao de um patio = movimentacoes ABERTAS nele.
ALTER TABLE movimentacao ADD COLUMN patio_id BIGINT;
ALTER TABLE movimentacao ADD CONSTRAINT fk_movimentacao_patio
    FOREIGN KEY (patio_id) REFERENCES patio (id) ON DELETE RESTRICT;
CREATE INDEX ix_movimentacao_patio ON movimentacao (patio_id);
