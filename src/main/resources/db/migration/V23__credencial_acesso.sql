CREATE TABLE credencial_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    patio_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    item_pedido_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    codigo_publico VARCHAR(36) NOT NULL,
    numero_unidade INTEGER NOT NULL,
    origem VARCHAR(30) NOT NULL,
    categoria VARCHAR(30) NOT NULL,
    direito VARCHAR(40) NOT NULL,
    inicio_validade TIMESTAMPTZ NOT NULL,
    fim_validade TIMESTAMPTZ NOT NULL,
    meio_preferido VARCHAR(20) NOT NULL,
    placa_veiculo VARCHAR(7),
    status VARCHAR(30) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_credencial_pedido_tenant
        FOREIGN KEY (pedido_id, organizacao_id)
        REFERENCES pedido(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_credencial_item_pedido
        FOREIGN KEY (item_pedido_id, pedido_id)
        REFERENCES item_pedido(id, pedido_id) ON DELETE RESTRICT,
    CONSTRAINT fk_credencial_patio_tenant
        FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_credencial_codigo_publico UNIQUE (codigo_publico),
    CONSTRAINT uq_credencial_item_unidade UNIQUE (item_pedido_id, numero_unidade),
    CONSTRAINT ck_credencial_codigo CHECK (
        codigo_publico ~ '^CRD-[A-F0-9]{32}$'
    ),
    CONSTRAINT ck_credencial_numero_unidade CHECK (numero_unidade > 0),
    CONSTRAINT ck_credencial_origem CHECK (origem IN ('PEDIDO')),
    CONSTRAINT ck_credencial_categoria CHECK (
        categoria IN ('COMUM', 'VIP', 'PCD', 'STAFF', 'ONIBUS', 'VAN', 'CORTESIA')
    ),
    CONSTRAINT ck_credencial_direito CHECK (direito IN ('ESTACIONAMENTO_EVENTO')),
    CONSTRAINT ck_credencial_validade CHECK (fim_validade > inicio_validade),
    CONSTRAINT ck_credencial_meio CHECK (meio_preferido IN ('QR', 'PLACA', 'RFID')),
    CONSTRAINT ck_credencial_placa CHECK (
        placa_veiculo IS NULL OR placa_veiculo ~ '^[A-Z0-9]{7}$'
    ),
    CONSTRAINT ck_credencial_status CHECK (status IN (
        'PENDENTE', 'ATIVA', 'DENTRO', 'CONSUMIDA', 'BLOQUEADA',
        'EXPIRADA', 'SUBSTITUIDA'
    )),
    CONSTRAINT ck_credencial_version CHECK (version >= 0)
);

CREATE INDEX ix_credencial_tenant_evento_status
    ON credencial_acesso (organizacao_id, evento_id, status, id);
CREATE INDEX ix_credencial_pedido
    ON credencial_acesso (pedido_id, item_pedido_id);
CREATE INDEX ix_credencial_patio_status
    ON credencial_acesso (patio_id, status);

