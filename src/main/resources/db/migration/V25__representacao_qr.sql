CREATE TABLE representacao_qr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    credencial_id BIGINT NOT NULL,
    numero_versao INTEGER NOT NULL,
    token_hash CHAR(64) NOT NULL,
    emitido_em TIMESTAMPTZ NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL,
    revogada_em TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_qr_credencial_tenant
        FOREIGN KEY (credencial_id, organizacao_id)
        REFERENCES credencial_acesso(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_qr_credencial_versao
        UNIQUE (credencial_id, numero_versao),
    CONSTRAINT uq_qr_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_qr_numero_versao CHECK (numero_versao > 0),
    CONSTRAINT ck_qr_token_hash CHECK (token_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_qr_validade CHECK (expira_em > emitido_em),
    CONSTRAINT ck_qr_revogacao CHECK (
        revogada_em IS NULL OR revogada_em >= emitido_em
    ),
    CONSTRAINT ck_qr_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_qr_ativo_credencial
    ON representacao_qr (credencial_id)
    WHERE revogada_em IS NULL;
CREATE INDEX ix_qr_tenant_credencial
    ON representacao_qr (organizacao_id, credencial_id, numero_versao DESC);
