ALTER TABLE alocacao_patio_evento
    ADD CONSTRAINT uq_alocacao_id_tenant_evento
        UNIQUE (id, organizacao_id, evento_id);

CREATE TABLE produto_estacionamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    alocacao_id BIGINT NOT NULL,
    nome VARCHAR(160) NOT NULL,
    categoria VARCHAR(30) NOT NULL,
    direito VARCHAR(40) NOT NULL,
    inicio_acesso TIMESTAMPTZ NOT NULL,
    fim_acesso TIMESTAMPTZ NOT NULL,
    quota INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RASCUNHO',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_produto_alocacao_tenant_evento
        FOREIGN KEY (alocacao_id, organizacao_id, evento_id)
        REFERENCES alocacao_patio_evento (id, organizacao_id, evento_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_produto_nome CHECK (length(btrim(nome)) BETWEEN 1 AND 160),
    CONSTRAINT ck_produto_categoria CHECK (
        categoria IN ('COMUM', 'VIP', 'PCD', 'STAFF', 'ONIBUS', 'VAN', 'CORTESIA')
    ),
    CONSTRAINT ck_produto_direito CHECK (direito IN ('ESTACIONAMENTO_EVENTO')),
    CONSTRAINT ck_produto_periodo CHECK (fim_acesso > inicio_acesso),
    CONSTRAINT ck_produto_quota CHECK (quota > 0),
    CONSTRAINT ck_produto_status CHECK (
        status IN ('RASCUNHO', 'PUBLICADO', 'SUSPENSO', 'ENCERRADO')
    ),
    CONSTRAINT ck_produto_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_produto_evento_nome_normalizado
    ON produto_estacionamento (evento_id, lower(btrim(nome)));
CREATE INDEX ix_produto_alocacao
    ON produto_estacionamento (alocacao_id);
CREATE INDEX ix_produto_evento_status
    ON produto_estacionamento (evento_id, status);
CREATE INDEX ix_produto_organizacao
    ON produto_estacionamento (organizacao_id);

CREATE TABLE produto_estacionamento_beneficio (
    produto_id BIGINT NOT NULL REFERENCES produto_estacionamento(id) ON DELETE CASCADE,
    ordem INTEGER NOT NULL,
    codigo VARCHAR(60) NOT NULL,
    PRIMARY KEY (produto_id, ordem),
    CONSTRAINT uq_produto_beneficio UNIQUE (produto_id, codigo),
    CONSTRAINT ck_produto_beneficio_ordem CHECK (ordem >= 0),
    CONSTRAINT ck_produto_beneficio_codigo CHECK (
        codigo ~ '^[A-Z][A-Z0-9_]{0,59}$'
    )
);

CREATE TABLE produto_estacionamento_restricao (
    produto_id BIGINT NOT NULL REFERENCES produto_estacionamento(id) ON DELETE CASCADE,
    ordem INTEGER NOT NULL,
    codigo VARCHAR(60) NOT NULL,
    PRIMARY KEY (produto_id, ordem),
    CONSTRAINT uq_produto_restricao UNIQUE (produto_id, codigo),
    CONSTRAINT ck_produto_restricao_ordem CHECK (ordem >= 0),
    CONSTRAINT ck_produto_restricao_codigo CHECK (
        codigo ~ '^[A-Z][A-Z0-9_]{0,59}$'
    )
);

