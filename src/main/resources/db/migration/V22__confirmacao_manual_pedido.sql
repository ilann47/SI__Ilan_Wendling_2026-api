ALTER TABLE pedido
    ADD CONSTRAINT uq_pedido_id_tenant UNIQUE (id, organizacao_id);

CREATE TABLE confirmacao_manual_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    pedido_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    meio_pagamento VARCHAR(30) NOT NULL,
    referencia_evidencia VARCHAR(200) NOT NULL,
    motivo VARCHAR(300) NOT NULL,
    status_conciliacao VARCHAR(30) NOT NULL DEFAULT 'PENDENTE_CONCILIACAO',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_confirmacao_manual_pedido_tenant
        FOREIGN KEY (pedido_id, organizacao_id)
        REFERENCES pedido (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_confirmacao_manual_pedido UNIQUE (pedido_id),
    CONSTRAINT ck_confirmacao_manual_meio CHECK (
        meio_pagamento ~ '^[A-Z][A-Z0-9_]{0,29}$'
    ),
    CONSTRAINT ck_confirmacao_manual_evidencia CHECK (
        length(btrim(referencia_evidencia)) BETWEEN 1 AND 200
    ),
    CONSTRAINT ck_confirmacao_manual_motivo CHECK (
        length(btrim(motivo)) BETWEEN 1 AND 300
    ),
    CONSTRAINT ck_confirmacao_manual_status CHECK (
        status_conciliacao IN ('PENDENTE_CONCILIACAO', 'CONCILIADA', 'DIVERGENTE')
    ),
    CONSTRAINT ck_confirmacao_manual_version CHECK (version >= 0)
);

CREATE INDEX ix_confirmacao_manual_tenant_status
    ON confirmacao_manual_pedido (organizacao_id, status_conciliacao, created_at);

INSERT INTO permissao (codigo, nome)
