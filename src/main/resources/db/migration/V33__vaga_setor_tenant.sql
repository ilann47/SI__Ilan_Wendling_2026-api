ALTER TABLE setor
    ADD CONSTRAINT uq_setor_id_organizacao UNIQUE (id, organizacao_id);

CREATE TABLE vaga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    setor_id BIGINT NOT NULL,
    codigo VARCHAR(40) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    acessivel BOOLEAN NOT NULL,
    posicao VARCHAR(120),
    status VARCHAR(20) NOT NULL DEFAULT 'LIVRE',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_vaga_setor_tenant FOREIGN KEY (setor_id, organizacao_id)
        REFERENCES setor (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT ck_vaga_tipo CHECK (
        tipo IN ('COMUM', 'VIP', 'PCD', 'STAFF', 'ONIBUS', 'VAN', 'CORTESIA')
    ),
    CONSTRAINT ck_vaga_status CHECK (status IN ('LIVRE', 'BLOQUEADA', 'MANUTENCAO')),
    CONSTRAINT ck_vaga_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_vaga_setor_codigo_normalizado
    ON vaga (setor_id, lower(btrim(codigo)));
CREATE INDEX ix_vaga_organizacao_setor
    ON vaga (organizacao_id, setor_id);
CREATE INDEX ix_vaga_setor_status
    ON vaga (setor_id, status);
