ALTER TABLE unidade_operacional
    ADD CONSTRAINT uq_unidade_operacional_id_organizacao
        UNIQUE (id, organizacao_id);

CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    venue_id BIGINT NOT NULL,
    nome VARCHAR(180) NOT NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    fuso_horario VARCHAR(60) NOT NULL,
    status VARCHAR(30) NOT NULL,
    external_id VARCHAR(160),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_evento_venue_tenant FOREIGN KEY (venue_id, organizacao_id)
        REFERENCES unidade_operacional (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT ck_evento_periodo CHECK (fim > inicio),
    CONSTRAINT ck_evento_status CHECK (status IN (
        'RASCUNHO', 'CONFIGURADO', 'PUBLICADO', 'VENDAS_ABERTAS',
        'VENDAS_ENCERRADAS', 'EM_OPERACAO', 'OPERACAO_ENCERRADA',
        'EM_CONCILIACAO', 'SUSPENSO', 'FINALIZADO', 'CANCELADO'
    )),
    CONSTRAINT ck_evento_version CHECK (version >= 0),
    CONSTRAINT ck_evento_external_id CHECK (
        external_id IS NULL OR length(btrim(external_id)) > 0
    )
);

CREATE UNIQUE INDEX uq_evento_external_id_organizacao
    ON evento (organizacao_id, lower(btrim(external_id)))
    WHERE external_id IS NOT NULL;
CREATE INDEX ix_evento_organizacao_status_inicio
    ON evento (organizacao_id, status, inicio);
CREATE INDEX ix_evento_venue_periodo
    ON evento (venue_id, inicio, fim);

CREATE TABLE requisicao_idempotente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    operacao VARCHAR(100) NOT NULL,
    chave VARCHAR(100) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    recurso_tipo VARCHAR(80) NOT NULL,
    recurso_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_requisicao_idempotente UNIQUE (
        organizacao_id, ator_id, operacao, chave
    ),
    CONSTRAINT ck_requisicao_idempotente_hash CHECK (
        request_hash ~ '^[0-9a-f]{64}$'
    )
);

CREATE INDEX ix_requisicao_idempotente_recurso
    ON requisicao_idempotente (recurso_tipo, recurso_id);

CREATE TABLE evento_outbox (
    event_id UUID PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    aggregate_version BIGINT NOT NULL,
    correlation_id VARCHAR(100) NOT NULL,
    causation_id UUID,
    schema_version INTEGER NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    tentativas INTEGER NOT NULL DEFAULT 0,
    disponivel_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    publicado_em TIMESTAMPTZ,
    ultimo_erro VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_evento_outbox_agregado UNIQUE (
        aggregate_type, aggregate_id, aggregate_version, event_type
    ),
    CONSTRAINT ck_evento_outbox_version CHECK (
        aggregate_version >= 0 AND schema_version > 0
    ),
    CONSTRAINT ck_evento_outbox_status CHECK (
        status IN ('PENDENTE', 'PROCESSANDO', 'PUBLICADO', 'FALHOU')
    ),
    CONSTRAINT ck_evento_outbox_tentativas CHECK (tentativas >= 0),
    CONSTRAINT ck_evento_outbox_payload CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX ix_evento_outbox_pendente
    ON evento_outbox (status, disponivel_em, occurred_at)
    WHERE status IN ('PENDENTE', 'FALHOU');
CREATE INDEX ix_evento_outbox_organizacao
    ON evento_outbox (organizacao_id, occurred_at DESC);

