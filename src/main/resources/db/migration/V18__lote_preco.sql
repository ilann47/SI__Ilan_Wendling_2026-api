ALTER TABLE produto_estacionamento
    ADD CONSTRAINT uq_produto_id_tenant UNIQUE (id, organizacao_id);

CREATE TABLE lote_preco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    produto_id BIGINT NOT NULL,
    nome VARCHAR(160) NOT NULL,
    preco NUMERIC(19,2) NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    inicio_venda TIMESTAMPTZ NOT NULL,
    fim_venda TIMESTAMPTZ NOT NULL,
    quantidade INTEGER NOT NULL,
    prioridade INTEGER NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_lote_preco_produto_tenant
        FOREIGN KEY (produto_id, organizacao_id)
        REFERENCES produto_estacionamento (id, organizacao_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_lote_preco_nome CHECK (length(btrim(nome)) BETWEEN 1 AND 160),
    CONSTRAINT ck_lote_preco_valor CHECK (preco >= 0),
    CONSTRAINT ck_lote_preco_moeda CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_lote_preco_periodo CHECK (fim_venda > inicio_venda),
    CONSTRAINT ck_lote_preco_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_lote_preco_prioridade CHECK (prioridade >= 0),
    CONSTRAINT ck_lote_preco_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_lote_preco_produto_nome_normalizado
    ON lote_preco (produto_id, lower(btrim(nome)));
CREATE INDEX ix_lote_preco_produto_periodo
    ON lote_preco (produto_id, inicio_venda, fim_venda);
CREATE INDEX ix_lote_preco_organizacao
    ON lote_preco (organizacao_id);

CREATE FUNCTION impedir_lote_preco_sobreposicao_ambigua()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM lote_preco existente
        WHERE existente.produto_id = NEW.produto_id
          AND existente.prioridade = NEW.prioridade
          AND existente.id <> COALESCE(NEW.id, -1)
          AND tstzrange(existente.inicio_venda, existente.fim_venda, '[)')
              && tstzrange(NEW.inicio_venda, NEW.fim_venda, '[)')
    ) THEN
        RAISE EXCEPTION 'Lotes do mesmo produto e prioridade nao podem se sobrepor.'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_lote_preco_sobreposicao_ambigua
BEFORE INSERT OR UPDATE OF produto_id, prioridade, inicio_venda, fim_venda
ON lote_preco
FOR EACH ROW EXECUTE FUNCTION impedir_lote_preco_sobreposicao_ambigua();
