ALTER TABLE produto_estacionamento
    ADD COLUMN quantidade_reservada INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN quantidade_vendida INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN quantidade_bloqueada INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_produto_saldos_nao_negativos CHECK (
        quantidade_reservada >= 0
        AND quantidade_vendida >= 0
        AND quantidade_bloqueada >= 0
    ),
    ADD CONSTRAINT ck_produto_saldo_dentro_quota CHECK (
        quantidade_reservada + quantidade_vendida + quantidade_bloqueada <= quota
    );

ALTER TABLE lote_preco
    ADD CONSTRAINT uq_lote_preco_id_tenant_produto
        UNIQUE (id, organizacao_id, produto_id);

CREATE TABLE reserva_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    quantidade INTEGER NOT NULL,
    canal VARCHAR(30) NOT NULL,
    referencia_comprador VARCHAR(160),
    chave_idempotencia VARCHAR(100) NOT NULL,
    lote_preco_id BIGINT NOT NULL,
    preco_unitario NUMERIC(19,2) NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'MANTIDA',
    expira_em TIMESTAMPTZ NOT NULL,
    finalizada_em TIMESTAMPTZ,
    motivo_finalizacao VARCHAR(300),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_reserva_produto_tenant
        FOREIGN KEY (produto_id, organizacao_id)
        REFERENCES produto_estacionamento (id, organizacao_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_lote_tenant_produto
        FOREIGN KEY (lote_preco_id, organizacao_id, produto_id)
        REFERENCES lote_preco (id, organizacao_id, produto_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_reserva_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_reserva_canal CHECK (canal ~ '^[A-Z][A-Z0-9_]{0,29}$'),
    CONSTRAINT ck_reserva_referencia CHECK (
        referencia_comprador IS NULL
        OR length(btrim(referencia_comprador)) BETWEEN 1 AND 160
    ),
    CONSTRAINT ck_reserva_chave CHECK (
        length(btrim(chave_idempotencia)) BETWEEN 1 AND 100
    ),
    CONSTRAINT ck_reserva_preco CHECK (preco_unitario >= 0),
    CONSTRAINT ck_reserva_moeda CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_reserva_status CHECK (
        status IN ('MANTIDA', 'CONFIRMADA', 'EXPIRADA', 'LIBERADA')
    ),
    CONSTRAINT ck_reserva_finalizacao CHECK (
        (status = 'MANTIDA' AND finalizada_em IS NULL AND motivo_finalizacao IS NULL)
        OR (status <> 'MANTIDA' AND finalizada_em IS NOT NULL)
    ),
    CONSTRAINT ck_reserva_expiracao CHECK (expira_em > created_at),
    CONSTRAINT ck_reserva_version CHECK (version >= 0)
);

CREATE INDEX ix_reserva_inventario_produto_status
    ON reserva_inventario (produto_id, status);
CREATE INDEX ix_reserva_inventario_ator
    ON reserva_inventario (organizacao_id, ator_id, created_at DESC);
CREATE INDEX ix_reserva_inventario_expiracao
    ON reserva_inventario (expira_em, id)
    WHERE status = 'MANTIDA';

