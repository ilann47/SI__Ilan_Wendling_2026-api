CREATE TABLE permissao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    nome VARCHAR(160) NOT NULL
);

CREATE TABLE papel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nome VARCHAR(160) NOT NULL,
    sistema BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE papel_permissao (
    papel_id BIGINT NOT NULL REFERENCES papel(id) ON DELETE RESTRICT,
    permissao_id BIGINT NOT NULL REFERENCES permissao(id) ON DELETE RESTRICT,
    PRIMARY KEY (papel_id, permissao_id)
);

CREATE TABLE atribuicao_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membro_organizacao_id BIGINT NOT NULL REFERENCES membro_organizacao(id) ON DELETE RESTRICT,
    papel_id BIGINT NOT NULL REFERENCES papel(id) ON DELETE RESTRICT,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    escopo_tipo VARCHAR(30) NOT NULL,
    escopo_id BIGINT NOT NULL,
    concedido_em TIMESTAMPTZ NOT NULL,
    revogado_em TIMESTAMPTZ,
    motivo_revogacao VARCHAR(300),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_atribuicao_escopo CHECK (escopo_tipo = 'ORGANIZACAO' AND escopo_id = organizacao_id),
    CONSTRAINT ck_atribuicao_revogacao CHECK (
        (revogado_em IS NULL AND motivo_revogacao IS NULL)
        OR (revogado_em IS NOT NULL AND motivo_revogacao IS NOT NULL)
    ),
    CONSTRAINT ck_atribuicao_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_atribuicao_acesso_vigente
    ON atribuicao_acesso (membro_organizacao_id, papel_id, escopo_tipo, escopo_id)
    WHERE revogado_em IS NULL;
CREATE INDEX ix_atribuicao_acesso_contexto
    ON atribuicao_acesso (membro_organizacao_id, organizacao_id) WHERE revogado_em IS NULL;

