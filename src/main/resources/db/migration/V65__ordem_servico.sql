CREATE TABLE ordem_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    numero VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RASCUNHO',
    data_abertura DATE NOT NULL,
    previsao_conclusao DATE,
    iniciada_em TIMESTAMPTZ,
    concluida_em TIMESTAMPTZ,
    moeda VARCHAR(3) NOT NULL DEFAULT 'BRL',
    subtotal NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL DEFAULT 0,
    observacao VARCHAR(500),
    motivo_cancelamento VARCHAR(300),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_ordem_servico_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_ordem_servico_cliente_tenant FOREIGN KEY (organizacao_id, cliente_id)
        REFERENCES cliente(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_ordem_servico_tenant_id UNIQUE (organizacao_id, id),
    CONSTRAINT uq_ordem_servico_numero UNIQUE (organizacao_id, numero),
    CONSTRAINT ck_ordem_servico_status CHECK
        (status IN ('RASCUNHO','EM_EXECUCAO','CONCLUIDA','CANCELADA')),
    CONSTRAINT ck_ordem_servico_datas CHECK
        (previsao_conclusao IS NULL OR previsao_conclusao >= data_abertura),
    CONSTRAINT ck_ordem_servico_valores CHECK
        (subtotal >= 0 AND valor_desconto >= 0 AND valor_desconto <= subtotal
         AND valor_total = subtotal - valor_desconto),
    CONSTRAINT ck_ordem_servico_transicoes CHECK (
        (status='RASCUNHO' AND iniciada_em IS NULL AND concluida_em IS NULL)
        OR (status='EM_EXECUCAO' AND iniciada_em IS NOT NULL AND concluida_em IS NULL)
        OR (status='CONCLUIDA' AND iniciada_em IS NOT NULL AND concluida_em IS NOT NULL)
        OR status='CANCELADA')
);

CREATE TABLE item_ordem_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    ordem_servico_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,
    sequencia INTEGER NOT NULL,
    descricao_snapshot VARCHAR(255) NOT NULL,
    quantidade NUMERIC(15,3) NOT NULL,
    valor_unitario NUMERIC(15,2) NOT NULL,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_ordem_servico_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_ordem_servico_ordem_tenant FOREIGN KEY
        (organizacao_id, ordem_servico_id)
        REFERENCES ordem_servico(organizacao_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_item_ordem_servico_servico_tenant FOREIGN KEY
        (organizacao_id, servico_id)
        REFERENCES servico(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_item_ordem_servico_sequencia UNIQUE (ordem_servico_id, sequencia),
    CONSTRAINT uq_item_ordem_servico_servico UNIQUE (ordem_servico_id, servico_id),
    CONSTRAINT ck_item_ordem_servico_sequencia CHECK (sequencia > 0),
    CONSTRAINT ck_item_ordem_servico_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_ordem_servico_valores CHECK (
        valor_unitario >= 0 AND valor_desconto >= 0
        AND valor_desconto <= quantidade * valor_unitario
        AND valor_total = quantidade * valor_unitario - valor_desconto)
);

ALTER TABLE nota_servico ADD COLUMN ordem_servico_id BIGINT;
ALTER TABLE nota_servico ADD CONSTRAINT fk_nota_servico_ordem_tenant
    FOREIGN KEY (organizacao_id, ordem_servico_id)
    REFERENCES ordem_servico(organizacao_id, id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_nota_servico_ordem_servico
    ON nota_servico(ordem_servico_id) WHERE ordem_servico_id IS NOT NULL;

CREATE INDEX ix_ordem_servico_organizacao_status
    ON ordem_servico(organizacao_id, status, data_abertura DESC, id DESC);

CREATE FUNCTION impedir_owner_ordem_servico_v65() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NEW.organizacao_id IS DISTINCT FROM OLD.organizacao_id THEN
        RAISE EXCEPTION 'owner da ordem de servico e imutavel [ck_ordem_servico_owner_imutavel]'
            USING ERRCODE='23514', CONSTRAINT='ck_ordem_servico_owner_imutavel';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_00_ordem_servico_owner
BEFORE UPDATE OF organizacao_id ON ordem_servico
FOR EACH ROW EXECUTE FUNCTION impedir_owner_ordem_servico_v65();

CREATE FUNCTION validar_nota_ordem_servico_v65() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE owner_ref BIGINT; cliente_ref BIGINT; status_ref VARCHAR(30); total_ref NUMERIC(15,2);
BEGIN
    IF NEW.ordem_servico_id IS NULL THEN RETURN NEW; END IF;
    SELECT organizacao_id, cliente_id, status, valor_total
      INTO owner_ref, cliente_ref, status_ref, total_ref
      FROM ordem_servico WHERE id=NEW.ordem_servico_id;
    IF NOT FOUND OR owner_ref IS DISTINCT FROM NEW.organizacao_id THEN
        RAISE EXCEPTION 'owner da nota diverge da ordem [fk_nota_servico_ordem_tenant]'
            USING ERRCODE='23503', CONSTRAINT='fk_nota_servico_ordem_tenant';
    END IF;
    IF cliente_ref IS DISTINCT FROM NEW.cliente_id THEN
        RAISE EXCEPTION 'cliente da nota diverge da ordem [ck_nota_ordem_servico_cliente]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_ordem_servico_cliente';
    END IF;
    IF status_ref <> 'CONCLUIDA' THEN
        RAISE EXCEPTION 'ordem precisa estar concluida [ck_nota_ordem_servico_concluida]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_ordem_servico_concluida';
    END IF;
    IF total_ref IS DISTINCT FROM NEW.valor_total THEN
        RAISE EXCEPTION 'valor da nota diverge da ordem [ck_nota_ordem_servico_valor]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_ordem_servico_valor';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_nota_ordem_servico_v65
BEFORE INSERT OR UPDATE OF organizacao_id, ordem_servico_id, cliente_id, valor_total
ON nota_servico FOR EACH ROW EXECUTE FUNCTION validar_nota_ordem_servico_v65();

