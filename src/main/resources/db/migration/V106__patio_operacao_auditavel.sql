-- Somente novos metadados: nenhum valor de documento antigo é recalculado.
CREATE TABLE patio_pagamento_dinheiro (
    organizacao_id BIGINT NOT NULL,
    movimentacao_id BIGINT NOT NULL,
    fase VARCHAR(7) NOT NULL CHECK(fase IN ('ENTRADA','SAIDA')),
    turno_id BIGINT NOT NULL,
    recebido_micros NUMERIC(24,0) NOT NULL CHECK(recebido_micros >= 0),
    troco_micros NUMERIC(24,0) NOT NULL CHECK(troco_micros >= 0 AND troco_micros <= recebido_micros),
    PRIMARY KEY(organizacao_id,movimentacao_id,fase),
    FOREIGN KEY(organizacao_id,movimentacao_id) REFERENCES movimentacao(organizacao_id,id),
    FOREIGN KEY(organizacao_id,turno_id) REFERENCES patio_turno(organizacao_id,id)
);
CREATE TABLE patio_operacao_correcao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    movimentacao_id BIGINT NOT NULL,
    chave UUID NOT NULL,
    acao VARCHAR(30) NOT NULL CHECK(acao IN ('CORRIGIR_PLACA','CANCELAR_ESTADIA','CORRIGIR_MEIO')),
    motivo VARCHAR(300) NOT NULL CHECK(length(trim(motivo)) BETWEEN 10 AND 300),
    placa_anterior VARCHAR(10),
    placa_nova VARCHAR(10),
    meio_novo VARCHAR(16) CHECK(meio_novo IN ('DINHEIRO','PIX','CARTAO')),
    criado_em TIMESTAMPTZ NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    UNIQUE(organizacao_id,chave),
    UNIQUE(organizacao_id,id),
    FOREIGN KEY(organizacao_id,movimentacao_id) REFERENCES movimentacao(organizacao_id,id)
);
CREATE UNIQUE INDEX uq_patio_operacao_cancelada ON patio_operacao_correcao(organizacao_id,movimentacao_id)
    WHERE acao='CANCELAR_ESTADIA';
CREATE TABLE patio_operacao_ajuste (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    movimentacao_id BIGINT NOT NULL,
    turno_id BIGINT NOT NULL,
    correcao_id BIGINT NOT NULL,
    meio VARCHAR(16) NOT NULL CHECK(meio IN ('DINHEIRO','PIX','CARTAO')),
    valor_micros NUMERIC(24,0) NOT NULL CHECK(valor_micros <> 0),
    UNIQUE(correcao_id,meio),
    FOREIGN KEY(organizacao_id,movimentacao_id) REFERENCES movimentacao(organizacao_id,id),
    FOREIGN KEY(organizacao_id,turno_id) REFERENCES patio_turno(organizacao_id,id),
    FOREIGN KEY(organizacao_id,correcao_id) REFERENCES patio_operacao_correcao(organizacao_id,id)
);
CREATE INDEX ix_patio_ajuste_turno ON patio_operacao_ajuste(organizacao_id,turno_id);
ALTER TABLE patio_evento_fiscal DROP CONSTRAINT patio_evento_fiscal_status_check;
