ALTER TABLE evento
    ADD CONSTRAINT uq_evento_id_organizacao UNIQUE (id, organizacao_id);

ALTER TABLE patio
    ADD CONSTRAINT uq_patio_id_organizacao UNIQUE (id, organizacao_id);

CREATE TABLE alocacao_patio_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    patio_id BIGINT NOT NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    capacidade_operacional INTEGER NOT NULL,
    capacidade_vendavel INTEGER NOT NULL,
    capacidade_reservada INTEGER NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_alocacao_evento_tenant FOREIGN KEY (evento_id, organizacao_id)
        REFERENCES evento (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_alocacao_patio_tenant FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_alocacao_evento_patio UNIQUE (evento_id, patio_id),
    CONSTRAINT ck_alocacao_periodo CHECK (fim > inicio),
    CONSTRAINT ck_alocacao_capacidades CHECK (
        capacidade_operacional > 0
        AND capacidade_vendavel >= 0
        AND capacidade_reservada >= 0
        AND capacidade_vendavel + capacidade_reservada <= capacidade_operacional
    ),
    CONSTRAINT ck_alocacao_version CHECK (version >= 0)
);

CREATE INDEX ix_alocacao_patio_periodo
    ON alocacao_patio_evento (patio_id, inicio, fim);
CREATE INDEX ix_alocacao_evento
    ON alocacao_patio_evento (evento_id);
CREATE INDEX ix_alocacao_organizacao
    ON alocacao_patio_evento (organizacao_id);

