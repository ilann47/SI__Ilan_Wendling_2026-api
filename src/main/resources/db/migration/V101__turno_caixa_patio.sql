CREATE TABLE patio_turno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id),
    operador_id BIGINT NOT NULL REFERENCES usuario(id),
    aberto_em TIMESTAMPTZ NOT NULL,
    fechado_em TIMESTAMPTZ,
    fundo_troco_micros NUMERIC(20,0) NOT NULL CHECK (fundo_troco_micros >= 0),
    dinheiro_contado_micros NUMERIC(20,0) CHECK (dinheiro_contado_micros >= 0),
    CONSTRAINT uq_patio_turno_org UNIQUE (organizacao_id, id),
    CONSTRAINT ck_patio_turno_fechamento CHECK (
        (fechado_em IS NULL AND dinheiro_contado_micros IS NULL)
        OR (fechado_em IS NOT NULL AND fechado_em >= aberto_em AND dinheiro_contado_micros IS NOT NULL))
);
CREATE UNIQUE INDEX uq_patio_turno_aberto ON patio_turno(organizacao_id, operador_id) WHERE fechado_em IS NULL;
CREATE INDEX ix_patio_turno_historico ON patio_turno(organizacao_id, operador_id, id DESC);

ALTER TABLE movimentacao
    ADD CONSTRAINT uq_movimentacao_org UNIQUE (organizacao_id, id),
    ADD COLUMN patio_turno_entrada_id BIGINT,
    ADD CONSTRAINT fk_movimentacao_patio_turno FOREIGN KEY (organizacao_id, patio_turno_entrada_id)
        REFERENCES patio_turno(organizacao_id, id),
    ADD CONSTRAINT ck_movimentacao_turno_org CHECK (patio_turno_entrada_id IS NULL OR organizacao_id IS NOT NULL);

CREATE TABLE patio_checkout (
    movimentacao_id BIGINT PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    turno_id BIGINT NOT NULL,
    chave UUID NOT NULL UNIQUE,
    calculado_em TIMESTAMPTZ NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL CHECK (expira_em > calculado_em),
    valor_micros NUMERIC(20,0) NOT NULL CHECK (valor_micros >= 0),
    confirmado_em TIMESTAMPTZ,
    meio VARCHAR(16),
    FOREIGN KEY (organizacao_id, movimentacao_id) REFERENCES movimentacao(organizacao_id, id),
    FOREIGN KEY (organizacao_id, turno_id) REFERENCES patio_turno(organizacao_id, id),
    CONSTRAINT ck_patio_checkout_confirmacao CHECK (
        (confirmado_em IS NULL AND meio IS NULL)
        OR (confirmado_em IS NOT NULL AND confirmado_em >= calculado_em AND meio IS NOT NULL AND (
            (valor_micros = 0 AND meio = 'SEM_COBRANCA')
            OR (valor_micros > 0 AND meio IN ('DINHEIRO', 'PIX', 'CARTAO')))))
);
CREATE INDEX ix_patio_checkout_caixa ON patio_checkout(organizacao_id, turno_id) WHERE confirmado_em IS NOT NULL;
