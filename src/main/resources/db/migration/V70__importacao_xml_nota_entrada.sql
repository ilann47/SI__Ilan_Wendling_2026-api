CREATE TABLE importacao_nota_entrada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    chave VARCHAR(44) NOT NULL,
    xml_original BYTEA NOT NULL,
    xml_hash VARCHAR(64) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    emitente_nome VARCHAR(120) NOT NULL,
    total NUMERIC(15,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    fornecedor_id BIGINT,
    local_estoque_id BIGINT,
    condicao_pagamento_id BIGINT,
    ordem_compra_id BIGINT,
    recebimento_compra_id BIGINT,
    nota_entrada_id BIGINT,
    conferido_por BIGINT REFERENCES usuario(id) ON DELETE RESTRICT,
    conferido_em TIMESTAMPTZ,
    revisado_em TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_importacao_xml_tenant_chave UNIQUE (organizacao_id,chave),
    CONSTRAINT uq_importacao_xml_contexto UNIQUE (organizacao_id,id),
    CONSTRAINT uq_importacao_xml_nota UNIQUE (nota_entrada_id),
    CONSTRAINT ck_importacao_xml_chave CHECK (chave ~ '^[0-9]{44}$'),
    CONSTRAINT ck_importacao_xml_tamanho CHECK (octet_length(xml_original) BETWEEN 1 AND 2097152),
    CONSTRAINT ck_importacao_xml_estado CHECK (status IN ('IMPORTADA','CONCILIADA','CONFERIDA','CONFIRMADA')),
    CONSTRAINT ck_importacao_xml_valores CHECK (total>=0 AND version>=0),
    CONSTRAINT ck_importacao_xml_conciliacao CHECK (status='IMPORTADA' OR (fornecedor_id IS NOT NULL AND local_estoque_id IS NOT NULL)),
    CONSTRAINT ck_importacao_xml_confirmada CHECK ((status='CONFIRMADA')=(nota_entrada_id IS NOT NULL)),
    CONSTRAINT ck_importacao_xml_conferida CHECK (status NOT IN ('CONFERIDA','CONFIRMADA') OR (conferido_por IS NOT NULL AND conferido_em IS NOT NULL)),
    CONSTRAINT ck_importacao_xml_recebimento CHECK (recebimento_compra_id IS NULL OR ordem_compra_id IS NOT NULL),
    FOREIGN KEY (organizacao_id,fornecedor_id) REFERENCES fornecedor(organizacao_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (local_estoque_id,organizacao_id) REFERENCES local_estoque(id,organizacao_id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,condicao_pagamento_id) REFERENCES condicao_pagamento(organizacao_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,ordem_compra_id) REFERENCES ordem_compra(organizacao_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,ordem_compra_id,recebimento_compra_id) REFERENCES recebimento_compra(organizacao_id,ordem_compra_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,nota_entrada_id) REFERENCES nota_entrada(organizacao_id,id) ON DELETE RESTRICT
);
CREATE INDEX ix_importacao_xml_lista ON importacao_nota_entrada(organizacao_id,created_at DESC,id DESC);

CREATE TABLE item_importacao_nota_entrada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    importacao_id BIGINT NOT NULL,
    sequencia INTEGER NOT NULL,
    produto_id BIGINT NOT NULL,
    unidade_destino VARCHAR(10) NOT NULL,
    fator_conversao NUMERIC(18,6) NOT NULL,
    quantidade NUMERIC(15,3) NOT NULL,
    valor_unitario NUMERIC(15,2) NOT NULL,
    quantidade_conferida NUMERIC(15,3),
    ordem_compra_id BIGINT,
    item_ordem_compra_id BIGINT,
    motivo_divergencia VARCHAR(300),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_item_importacao_sequencia UNIQUE (importacao_id,sequencia),
    CONSTRAINT ck_item_importacao_sequencia CHECK (sequencia BETWEEN 1 AND 990),
    CONSTRAINT ck_item_importacao_valores CHECK (fator_conversao>0 AND quantidade>0 AND valor_unitario>=0 AND (quantidade_conferida IS NULL OR quantidade_conferida>=0)),
    CONSTRAINT ck_item_importacao_ordem CHECK ((ordem_compra_id IS NULL)=(item_ordem_compra_id IS NULL)),
    FOREIGN KEY (organizacao_id,importacao_id) REFERENCES importacao_nota_entrada(organizacao_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,produto_id) REFERENCES produto(organizacao_id,id) ON DELETE RESTRICT,
    FOREIGN KEY (organizacao_id,ordem_compra_id,item_ordem_compra_id,produto_id)
        REFERENCES item_ordem_compra(organizacao_id,ordem_compra_id,id,produto_id) ON DELETE RESTRICT
);

CREATE FUNCTION preservar_importacao_xml_v70() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.organizacao_id IS DISTINCT FROM OLD.organizacao_id OR NEW.chave IS DISTINCT FROM OLD.chave
       OR NEW.xml_original IS DISTINCT FROM OLD.xml_original OR NEW.xml_hash IS DISTINCT FROM OLD.xml_hash
       OR NEW.ator_id IS DISTINCT FROM OLD.ator_id THEN
        RAISE EXCEPTION 'Identidade e XML de origem são imutáveis' USING ERRCODE='23514';
    END IF;
    IF OLD.status='CONFIRMADA' AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'Importação confirmada é imutável' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_importacao_xml_imutavel BEFORE UPDATE ON importacao_nota_entrada
FOR EACH ROW EXECUTE FUNCTION preservar_importacao_xml_v70();
