CREATE TABLE tentativa_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    patio_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    credencial_id BIGINT,
    representacao_qr_id BIGINT,
    direcao VARCHAR(20) NOT NULL,
    origem_leitura VARCHAR(20) NOT NULL,
    faixa VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL,
    motivo VARCHAR(50),
    ocupacao_resultante INTEGER,
    recebido_em TIMESTAMPTZ NOT NULL,
    decidido_em TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_tentativa_evento_tenant
        FOREIGN KEY (evento_id, organizacao_id)
        REFERENCES evento(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tentativa_patio_tenant
        FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tentativa_credencial_tenant
        FOREIGN KEY (credencial_id, organizacao_id)
        REFERENCES credencial_acesso(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tentativa_qr
        FOREIGN KEY (representacao_qr_id)
        REFERENCES representacao_qr(id) ON DELETE RESTRICT,
    CONSTRAINT ck_tentativa_direcao CHECK (direcao = 'ENTRADA'),
    CONSTRAINT ck_tentativa_origem CHECK (origem_leitura = 'QR'),
    CONSTRAINT ck_tentativa_status CHECK (status IN (
        'RECEBIDA', 'AVALIANDO', 'AUTORIZADA', 'RECUSADA'
    )),
    CONSTRAINT ck_tentativa_decisao CHECK (
        (status IN ('RECEBIDA', 'AVALIANDO')
            AND motivo IS NULL AND decidido_em IS NULL)
        OR (status = 'RECUSADA'
            AND motivo IS NOT NULL AND decidido_em IS NOT NULL
            AND ocupacao_resultante IS NULL)
        OR (status = 'AUTORIZADA'
            AND motivo = 'AUTORIZADA' AND decidido_em IS NOT NULL
            AND credencial_id IS NOT NULL AND representacao_qr_id IS NOT NULL
            AND ocupacao_resultante IS NOT NULL AND ocupacao_resultante > 0)
    ),
    CONSTRAINT ck_tentativa_motivo CHECK (motivo IS NULL OR motivo IN (
        'AUTORIZADA', 'CREDENCIAL_INVALIDA', 'CREDENCIAL_INATIVA',
        'FORA_DA_JANELA', 'EVENTO_FORA_DE_OPERACAO', 'PATIO_INCORRETO',
        'ENTRADA_DUPLICADA', 'PATIO_LOTADO'
    )),
    CONSTRAINT ck_tentativa_version CHECK (version >= 0)
);

CREATE INDEX ix_tentativa_tenant_evento_instante
    ON tentativa_acesso (organizacao_id, evento_id, recebido_em DESC, id DESC);
CREATE INDEX ix_tentativa_credencial_instante
    ON tentativa_acesso (credencial_id, recebido_em DESC)
    WHERE credencial_id IS NOT NULL;

CREATE TABLE presenca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    patio_id BIGINT NOT NULL,
    credencial_id BIGINT NOT NULL,
    tentativa_checkin_id BIGINT NOT NULL UNIQUE
        REFERENCES tentativa_acesso(id) ON DELETE RESTRICT,
    checkin_em TIMESTAMPTZ NOT NULL,
    checkout_em TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_presenca_id_tenant UNIQUE (id, organizacao_id),
    CONSTRAINT fk_presenca_evento_tenant
        FOREIGN KEY (evento_id, organizacao_id)
        REFERENCES evento(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_presenca_patio_tenant
        FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_presenca_credencial_tenant
        FOREIGN KEY (credencial_id, organizacao_id)
        REFERENCES credencial_acesso(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT ck_presenca_status CHECK (status IN ('DENTRO', 'FORA')),
    CONSTRAINT ck_presenca_checkout CHECK (
        (status = 'DENTRO' AND checkout_em IS NULL)
        OR (status = 'FORA' AND checkout_em IS NOT NULL AND checkout_em >= checkin_em)
    ),
    CONSTRAINT ck_presenca_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_presenca_aberta_credencial
    ON presenca (credencial_id) WHERE checkout_em IS NULL;
CREATE INDEX ix_presenca_ocupacao
    ON presenca (organizacao_id, evento_id, patio_id, status);

CREATE TABLE sessao_estacionamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    patio_id BIGINT NOT NULL,
    credencial_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    item_pedido_id BIGINT NOT NULL,
    presenca_id BIGINT NOT NULL UNIQUE,
    tentativa_entrada_id BIGINT NOT NULL UNIQUE,
    origem_direito VARCHAR(30) NOT NULL,
    placa_veiculo VARCHAR(7),
    entrada_em TIMESTAMPTZ NOT NULL,
    saida_em TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_sessao_evento_tenant
        FOREIGN KEY (evento_id, organizacao_id)
        REFERENCES evento(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_patio_tenant
        FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_credencial_tenant
        FOREIGN KEY (credencial_id, organizacao_id)
        REFERENCES credencial_acesso(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_pedido_tenant
        FOREIGN KEY (pedido_id, organizacao_id)
        REFERENCES pedido(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_item_pedido
        FOREIGN KEY (item_pedido_id, pedido_id, patio_id)
        REFERENCES item_pedido(id, pedido_id, patio_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_presenca_tenant
        FOREIGN KEY (presenca_id, organizacao_id)
        REFERENCES presenca(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_tentativa
        FOREIGN KEY (tentativa_entrada_id)
        REFERENCES tentativa_acesso(id) ON DELETE RESTRICT,
    CONSTRAINT ck_sessao_origem CHECK (origem_direito = 'PEDIDO_EVENTO'),
    CONSTRAINT ck_sessao_placa CHECK (
        placa_veiculo IS NULL OR placa_veiculo ~ '^[A-Z0-9]{7}$'
    ),
    CONSTRAINT ck_sessao_status CHECK (status IN ('ABERTA', 'ENCERRADA', 'CANCELADA')),
    CONSTRAINT ck_sessao_saida CHECK (
        (status = 'ABERTA' AND saida_em IS NULL)
        OR (status IN ('ENCERRADA', 'CANCELADA')
            AND saida_em IS NOT NULL AND saida_em >= entrada_em)
    ),
    CONSTRAINT ck_sessao_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_sessao_aberta_credencial
    ON sessao_estacionamento (credencial_id) WHERE status = 'ABERTA';
CREATE INDEX ix_sessao_tenant_evento_patio_status
    ON sessao_estacionamento (organizacao_id, evento_id, patio_id, status);

