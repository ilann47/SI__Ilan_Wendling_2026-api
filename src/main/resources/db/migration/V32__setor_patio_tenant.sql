CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    patio_id BIGINT NOT NULL,
    codigo VARCHAR(40) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    capacidade INTEGER NOT NULL,
    categorias VARCHAR(20)[] NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_setor_patio_tenant FOREIGN KEY (patio_id, organizacao_id)
        REFERENCES patio (id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT ck_setor_capacidade CHECK (capacidade > 0),
    CONSTRAINT ck_setor_categorias CHECK (
        cardinality(categorias) > 0
        AND categorias <@ ARRAY[
            'COMUM', 'VIP', 'PCD', 'STAFF', 'ONIBUS', 'VAN', 'CORTESIA'
        ]::VARCHAR[]
    ),
    CONSTRAINT ck_setor_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_setor_patio_codigo_normalizado
    ON setor (patio_id, lower(btrim(codigo)));
CREATE INDEX ix_setor_organizacao_patio
    ON setor (organizacao_id, patio_id);
CREATE INDEX ix_setor_patio_ativo
    ON setor (patio_id, ativo) WHERE ativo = TRUE;
