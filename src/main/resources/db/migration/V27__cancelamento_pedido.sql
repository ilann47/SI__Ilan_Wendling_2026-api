ALTER TABLE reserva_inventario DROP CONSTRAINT ck_reserva_status;
ALTER TABLE reserva_inventario
    ADD CONSTRAINT ck_reserva_status CHECK (
        status IN ('MANTIDA', 'CONFIRMADA', 'EXPIRADA', 'LIBERADA', 'CANCELADA')
    );

ALTER TABLE credencial_acesso
    ADD COLUMN bloqueada_em TIMESTAMPTZ,
    ADD COLUMN motivo_bloqueio VARCHAR(300),
    ADD CONSTRAINT ck_credencial_bloqueio CHECK (
        (status <> 'BLOQUEADA' AND bloqueada_em IS NULL AND motivo_bloqueio IS NULL)
        OR (status = 'BLOQUEADA' AND bloqueada_em IS NOT NULL
            AND length(btrim(motivo_bloqueio)) BETWEEN 1 AND 300)
    );

CREATE TABLE cancelamento_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    pedido_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    motivo VARCHAR(300) NOT NULL,
    status_pedido VARCHAR(30) NOT NULL,
    reembolso_necessario BOOLEAN NOT NULL,
    quantidade_liberada INTEGER NOT NULL,
    credenciais_bloqueadas INTEGER NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_cancelamento_pedido_tenant
        FOREIGN KEY (pedido_id, organizacao_id)
        REFERENCES pedido(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_cancelamento_pedido UNIQUE (pedido_id),
    CONSTRAINT ck_cancelamento_motivo CHECK (
        length(btrim(motivo)) BETWEEN 1 AND 300
    ),
    CONSTRAINT ck_cancelamento_status CHECK (
        status_pedido IN ('CANCELADO', 'EM_REEMBOLSO')
    ),
    CONSTRAINT ck_cancelamento_quantidades CHECK (
        quantidade_liberada > 0 AND credenciais_bloqueadas >= 0
    ),
    CONSTRAINT ck_cancelamento_reembolso CHECK (
        (reembolso_necessario AND status_pedido = 'EM_REEMBOLSO')
        OR (NOT reembolso_necessario AND status_pedido = 'CANCELADO')
    ),
    CONSTRAINT ck_cancelamento_version CHECK (version >= 0)
);

CREATE INDEX ix_cancelamento_tenant_created
    ON cancelamento_pedido (organizacao_id, created_at DESC, id DESC);

