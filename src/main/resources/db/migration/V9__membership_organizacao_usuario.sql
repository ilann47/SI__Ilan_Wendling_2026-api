-- Historia 2: vinculo temporal entre Usuario global e Organizacao.
-- Nao ha backfill: usuarios e dados legados permanecem sem tenant ate uma
-- associacao administrativa explicita.
CREATE TABLE membro_organizacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id  BIGINT       NOT NULL,
    usuario_id      BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    origem          VARCHAR(30)  NOT NULL,
    entrou_em       TIMESTAMPTZ  NOT NULL,
    suspenso_em     TIMESTAMPTZ,
    encerrado_em    TIMESTAMPTZ,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_membro_organizacao_organizacao
        FOREIGN KEY (organizacao_id) REFERENCES organizacao (id) ON DELETE RESTRICT,
    CONSTRAINT fk_membro_organizacao_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_membro_organizacao_status
        CHECK (status IN ('ATIVO', 'SUSPENSO', 'ENCERRADO')),
    CONSTRAINT ck_membro_organizacao_origem
        CHECK (origem IN ('ADMINISTRATIVA')),
    CONSTRAINT ck_membro_organizacao_version
        CHECK (version >= 0),
    CONSTRAINT ck_membro_organizacao_datas
        CHECK (
            (status = 'ATIVO' AND suspenso_em IS NULL AND encerrado_em IS NULL)
            OR (status = 'SUSPENSO' AND suspenso_em IS NOT NULL AND encerrado_em IS NULL)
            OR (status = 'ENCERRADO' AND suspenso_em IS NULL AND encerrado_em IS NOT NULL)
        ),
    CONSTRAINT ck_membro_organizacao_ordem_datas
        CHECK (
            (suspenso_em IS NULL OR suspenso_em >= entrou_em)
            AND (encerrado_em IS NULL OR encerrado_em >= entrou_em)
        )
);

-- Preserva historico encerrado e impede mais de um vinculo corrente, inclusive
-- a combinacao perigosa de um registro ATIVO com outro SUSPENSO.
CREATE UNIQUE INDEX uq_membro_organizacao_corrente
    ON membro_organizacao (organizacao_id, usuario_id)
    WHERE status <> 'ENCERRADO';

CREATE INDEX ix_membro_organizacao_usuario_status
    ON membro_organizacao (usuario_id, status);

CREATE INDEX ix_membro_organizacao_organizacao_status
    ON membro_organizacao (organizacao_id, status);
