-- Fundacao multiempresa: agregado Organizacao.
-- Membership e ownership dos demais modulos serao introduzidos nas historias
-- seguintes; esta migration nao atribui dados legados a um tenant ficticio.
CREATE TABLE organizacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento      VARCHAR(14)  NOT NULL,
    razao_social   VARCHAR(160) NOT NULL,
    nome_fantasia  VARCHAR(160),
    moeda          VARCHAR(3)   NOT NULL,
    fuso_horario   VARCHAR(60)  NOT NULL,
    regiao         VARCHAR(8)   NOT NULL,
    plano          VARCHAR(30)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_organizacao_documento_normalizado
        CHECK (documento ~ '^[0-9]{14}$'),
    CONSTRAINT ck_organizacao_moeda
        CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_organizacao_regiao
        CHECK (regiao ~ '^[A-Z]{2}-[A-Z0-9]{1,3}$'),
    CONSTRAINT ck_organizacao_plano
        CHECK (plano ~ '^[A-Z][A-Z0-9_]{1,29}$'),
    CONSTRAINT ck_organizacao_status
        CHECK (status IN ('PROVISIONANDO', 'ATIVA', 'SUSPENSA', 'ENCERRADA')),
    CONSTRAINT ck_organizacao_version
        CHECK (version >= 0)
);

-- A expressao normalizada garante a unicidade no proprio PostgreSQL, mesmo se
-- uma futura carga tentar contornar a normalizacao da aplicacao. O CHECK acima
-- mantem o valor efetivamente armazenado em sua forma canonica.
CREATE UNIQUE INDEX uq_organizacao_documento_normalizado
    ON organizacao ((regexp_replace(documento, '[^0-9]', '', 'g')));
