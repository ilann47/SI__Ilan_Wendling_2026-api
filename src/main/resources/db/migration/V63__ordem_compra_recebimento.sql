CREATE TABLE ordem_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    fornecedor_id BIGINT NOT NULL,
    numero VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    data_emissao DATE NOT NULL,
    previsao_entrega DATE,
    moeda VARCHAR(3) NOT NULL,
    subtotal NUMERIC(15,2) NOT NULL,
    valor_frete NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL,
    observacao VARCHAR(500),
    motivo_cancelamento VARCHAR(300),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_ordem_compra_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_ordem_compra_fornecedor_tenant FOREIGN KEY (organizacao_id, fornecedor_id)
        REFERENCES fornecedor(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_ordem_compra_organizacao_id UNIQUE (organizacao_id, id),
    CONSTRAINT uq_ordem_compra_numero UNIQUE (organizacao_id, numero),
    CONSTRAINT ck_ordem_compra_status CHECK (status IN (
        'RASCUNHO','APROVADA','PARCIALMENTE_RECEBIDA','RECEBIDA','CANCELADA')),
    CONSTRAINT ck_ordem_compra_datas CHECK (
        previsao_entrega IS NULL OR previsao_entrega >= data_emissao),
    CONSTRAINT ck_ordem_compra_moeda CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_ordem_compra_valores CHECK (
        subtotal >= 0 AND valor_frete >= 0 AND valor_desconto >= 0
        AND valor_desconto <= subtotal + valor_frete
        AND valor_total = subtotal + valor_frete - valor_desconto),
    CONSTRAINT ck_ordem_compra_cancelamento CHECK (
        (status = 'CANCELADA' AND motivo_cancelamento IS NOT NULL
            AND length(btrim(motivo_cancelamento)) BETWEEN 1 AND 300)
        OR (status <> 'CANCELADA' AND motivo_cancelamento IS NULL)),
    CONSTRAINT ck_ordem_compra_version CHECK (version >= 0)
);

CREATE TABLE item_ordem_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    ordem_compra_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    sequencia INTEGER NOT NULL,
    quantidade_pedida NUMERIC(15,3) NOT NULL,
    quantidade_recebida NUMERIC(15,3) NOT NULL DEFAULT 0,
    valor_unitario NUMERIC(15,2) NOT NULL,
    valor_desconto NUMERIC(15,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(15,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_ordem_compra_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_ordem_compra_ordem_tenant FOREIGN KEY (organizacao_id, ordem_compra_id)
        REFERENCES ordem_compra(organizacao_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_item_ordem_compra_produto_tenant FOREIGN KEY (organizacao_id, produto_id)
        REFERENCES produto(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_item_ordem_compra_contexto UNIQUE
        (organizacao_id, ordem_compra_id, id, produto_id),
    CONSTRAINT uq_item_ordem_compra_sequencia UNIQUE (ordem_compra_id, sequencia),
    CONSTRAINT uq_item_ordem_compra_produto UNIQUE (ordem_compra_id, produto_id),
    CONSTRAINT ck_item_ordem_compra_sequencia CHECK (sequencia > 0),
    CONSTRAINT ck_item_ordem_compra_quantidades CHECK (
        quantidade_pedida > 0 AND quantidade_recebida >= 0
        AND quantidade_recebida <= quantidade_pedida),
    CONSTRAINT ck_item_ordem_compra_valores CHECK (
        valor_unitario >= 0 AND valor_desconto >= 0
        AND valor_desconto <= quantidade_pedida * valor_unitario
        AND valor_total = quantidade_pedida * valor_unitario - valor_desconto)
);

CREATE TABLE recebimento_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    ordem_compra_id BIGINT NOT NULL,
    local_estoque_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL,
    recebido_em TIMESTAMPTZ NOT NULL,
    observacao VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_recebimento_compra_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_recebimento_compra_ordem_tenant FOREIGN KEY (organizacao_id, ordem_compra_id)
        REFERENCES ordem_compra(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_recebimento_compra_local_tenant FOREIGN KEY (local_estoque_id, organizacao_id)
        REFERENCES local_estoque(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_recebimento_compra_ator FOREIGN KEY (ator_id)
        REFERENCES usuario(id) ON DELETE RESTRICT,
    CONSTRAINT uq_recebimento_compra_contexto UNIQUE
        (organizacao_id, ordem_compra_id, id),
    CONSTRAINT uq_recebimento_compra_organizacao_id UNIQUE (organizacao_id, id)
);

CREATE TABLE item_recebimento_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    ordem_compra_id BIGINT NOT NULL,
    recebimento_compra_id BIGINT NOT NULL,
    item_ordem_compra_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade NUMERIC(15,3) NOT NULL,
    custo_unitario NUMERIC(15,2) NOT NULL,
    movimento_estoque_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_recebimento_organizacao FOREIGN KEY (organizacao_id)
        REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_recebimento_recebimento FOREIGN KEY
        (organizacao_id, ordem_compra_id, recebimento_compra_id)
        REFERENCES recebimento_compra(organizacao_id, ordem_compra_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_recebimento_item_ordem FOREIGN KEY
        (organizacao_id, ordem_compra_id, item_ordem_compra_id, produto_id)
        REFERENCES item_ordem_compra(organizacao_id, ordem_compra_id, id, produto_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_item_recebimento_movimento FOREIGN KEY (movimento_estoque_id)
        REFERENCES movimento_estoque(id) ON DELETE RESTRICT,
    CONSTRAINT uq_item_recebimento_item UNIQUE (recebimento_compra_id, item_ordem_compra_id),
    CONSTRAINT uq_item_recebimento_movimento UNIQUE (movimento_estoque_id),
    CONSTRAINT ck_item_recebimento_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_recebimento_custo CHECK (custo_unitario >= 0)
);

