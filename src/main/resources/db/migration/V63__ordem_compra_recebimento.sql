    ON recebimento_compra(organizacao_id, ordem_compra_id, recebido_em DESC);

CREATE FUNCTION impedir_owner_ordem_compra_v63() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NEW.organizacao_id IS DISTINCT FROM OLD.organizacao_id THEN
        RAISE EXCEPTION 'owner da ordem de compra e imutavel [ck_ordem_compra_owner_imutavel]'
            USING ERRCODE='23514', CONSTRAINT='ck_ordem_compra_owner_imutavel';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_00_ordem_compra_owner
BEFORE UPDATE OF organizacao_id ON ordem_compra
FOR EACH ROW EXECUTE FUNCTION impedir_owner_ordem_compra_v63();

CREATE FUNCTION impedir_mutacao_recebimento_compra_v63() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    RAISE EXCEPTION 'recebimento de compra e imutavel [ck_recebimento_compra_append_only]'
        USING ERRCODE='23514', CONSTRAINT='ck_recebimento_compra_append_only';
END; $$;
CREATE TRIGGER tg_recebimento_compra_append_only
BEFORE UPDATE OR DELETE ON recebimento_compra
FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_recebimento_compra_v63();
CREATE TRIGGER tg_item_recebimento_compra_append_only
BEFORE UPDATE OR DELETE ON item_recebimento_compra
FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_recebimento_compra_v63();

CREATE FUNCTION validar_nota_recebimento_compra_v63() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE owner_ref BIGINT; fornecedor_ref BIGINT; local_ref BIGINT;
BEGIN
    IF NEW.recebimento_compra_id IS NULL THEN RETURN NEW; END IF;
    SELECT r.organizacao_id, o.fornecedor_id, r.local_estoque_id
      INTO owner_ref, fornecedor_ref, local_ref
      FROM recebimento_compra r
      JOIN ordem_compra o ON o.id=r.ordem_compra_id AND o.organizacao_id=r.organizacao_id
     WHERE r.id=NEW.recebimento_compra_id;
    IF NOT FOUND OR owner_ref IS DISTINCT FROM NEW.organizacao_id THEN
        RAISE EXCEPTION 'owner da nota diverge do recebimento [fk_nota_entrada_recebimento_tenant]'
            USING ERRCODE='23503', CONSTRAINT='fk_nota_entrada_recebimento_tenant';
    END IF;
    IF fornecedor_ref IS DISTINCT FROM NEW.fornecedor_id THEN
        RAISE EXCEPTION 'fornecedor da nota diverge da ordem [ck_nota_recebimento_fornecedor]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_recebimento_fornecedor';
    END IF;
    IF local_ref IS DISTINCT FROM NEW.local_estoque_id THEN
        RAISE EXCEPTION 'local da nota diverge do recebimento [ck_nota_recebimento_local]'
            USING ERRCODE='23514', CONSTRAINT='ck_nota_recebimento_local';
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER tg_nota_recebimento_compra_v63
BEFORE INSERT OR UPDATE OF organizacao_id, recebimento_compra_id, fornecedor_id, local_estoque_id
ON nota_entrada FOR EACH ROW EXECUTE FUNCTION validar_nota_recebimento_compra_v63();

