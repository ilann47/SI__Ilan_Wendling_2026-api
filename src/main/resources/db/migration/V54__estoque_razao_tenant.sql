       OR NEW.local_estoque_id IS DISTINCT FROM OLD.local_estoque_id THEN
        RAISE EXCEPTION 'owner e pontas do saldo sao imutaveis [ck_saldo_estoque_identidade_imutavel]'
            USING ERRCODE = '23514', CONSTRAINT = 'ck_saldo_estoque_identidade_imutavel';
    END IF;
    RETURN NEW;
END;
$$;

