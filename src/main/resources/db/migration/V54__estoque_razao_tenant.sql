CREATE FUNCTION validar_compensacao_movimento_estoque()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    original movimento_estoque%ROWTYPE;
BEGIN
    IF NEW.tipo <> 'COMPENSACAO' THEN
        RETURN NEW;
    END IF;
    IF NEW.id IS NOT NULL AND NEW.compensado_id = NEW.id THEN
        RAISE EXCEPTION 'movimento nao pode compensar a si proprio [ck_movimento_estoque_compensacao_valida]'
            USING ERRCODE = '23514',
                  CONSTRAINT = 'ck_movimento_estoque_compensacao_valida';
    END IF;
    SELECT * INTO original FROM movimento_estoque WHERE id = NEW.compensado_id;
    IF NOT FOUND THEN
        RETURN NEW;
    END IF;
    IF original.tipo = 'COMPENSACAO'
       OR NEW.delta <> -original.delta
       OR NEW.organizacao_id <> original.organizacao_id
       OR NEW.produto_id <> original.produto_id
       OR NEW.local_estoque_id <> original.local_estoque_id
       OR NEW.saldo_estoque_id <> original.saldo_estoque_id THEN
        RAISE EXCEPTION 'compensacao deve inverter movimento original nao compensatorio e manter as mesmas pontas [ck_movimento_estoque_compensacao_valida]'
            USING ERRCODE = '23514',
                  CONSTRAINT = 'ck_movimento_estoque_compensacao_valida';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_00_movimento_estoque_compensacao_valida
BEFORE INSERT ON movimento_estoque
FOR EACH ROW EXECUTE FUNCTION validar_compensacao_movimento_estoque();

CREATE FUNCTION validar_integridade_saldo_razao_estoque()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    saldo_id BIGINT;
    quantidade_atual NUMERIC(15,3);
    total_movimentos BIGINT;
    cadeia_valida BOOLEAN;
    ultimo_saldo NUMERIC(15,3);
BEGIN
    IF TG_TABLE_NAME = 'saldo_estoque' THEN
        saldo_id := NEW.id;
    ELSE
        saldo_id := NEW.saldo_estoque_id;
    END IF;

    SELECT quantidade INTO quantidade_atual
    FROM saldo_estoque WHERE id = saldo_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT count(*),
           COALESCE(bool_and(
               (ordem = 1 AND saldo_anterior = 0)
               OR (ordem > 1 AND saldo_anterior = saldo_posterior_anterior)
           ), true),
           max(saldo_posterior) FILTER (WHERE ordem_inversa = 1)
      INTO total_movimentos, cadeia_valida, ultimo_saldo
    FROM (
        SELECT saldo_anterior, saldo_posterior,
               row_number() OVER (ORDER BY id) AS ordem,
               row_number() OVER (ORDER BY id DESC) AS ordem_inversa,
               lag(saldo_posterior) OVER (ORDER BY id) AS saldo_posterior_anterior
        FROM movimento_estoque
        WHERE saldo_estoque_id = saldo_id
    ) cadeia;

    IF NOT cadeia_valida
       OR (total_movimentos = 0 AND quantidade_atual <> 0)
       OR (total_movimentos > 0 AND quantidade_atual <> ultimo_saldo) THEN
        RAISE EXCEPTION 'saldo e razao de estoque estao divergentes [ck_saldo_estoque_razao_consistente]'
            USING ERRCODE = '23514',
                  CONSTRAINT = 'ck_saldo_estoque_razao_consistente';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER ck_saldo_estoque_razao_consistente_saldo
AFTER INSERT OR UPDATE ON saldo_estoque
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validar_integridade_saldo_razao_estoque();

CREATE CONSTRAINT TRIGGER ck_saldo_estoque_razao_consistente_movimento
AFTER INSERT ON movimento_estoque
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validar_integridade_saldo_razao_estoque();

CREATE FUNCTION impedir_alteracao_owner_local_estoque()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NEW.organizacao_id IS DISTINCT FROM OLD.organizacao_id THEN
        RAISE EXCEPTION 'owner do local de estoque e imutavel [ck_local_estoque_owner_imutavel]'
            USING ERRCODE = '23514', CONSTRAINT = 'ck_local_estoque_owner_imutavel';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_00_local_estoque_owner_imutavel
BEFORE UPDATE OF organizacao_id ON local_estoque
FOR EACH ROW EXECUTE FUNCTION impedir_alteracao_owner_local_estoque();

CREATE FUNCTION impedir_alteracao_identidade_saldo_estoque()
RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
