CREATE TABLE local_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_local_estoque_organizacao
        FOREIGN KEY (organizacao_id) REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT uq_local_estoque_id_organizacao UNIQUE (id, organizacao_id),
    CONSTRAINT ck_local_estoque_nome CHECK (length(btrim(nome)) BETWEEN 1 AND 120),
    CONSTRAINT ck_local_estoque_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_local_estoque_organizacao_nome_normalizado
    ON local_estoque (organizacao_id, lower(btrim(nome)));
CREATE INDEX ix_local_estoque_organizacao_ativo
    ON local_estoque (organizacao_id, ativo, nome);

CREATE TABLE saldo_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    local_estoque_id BIGINT NOT NULL,
    quantidade NUMERIC(15,3) NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_saldo_estoque_organizacao
        FOREIGN KEY (organizacao_id) REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_saldo_estoque_produto_organizacao
        FOREIGN KEY (organizacao_id, produto_id)
        REFERENCES produto(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_saldo_estoque_local_organizacao
        FOREIGN KEY (local_estoque_id, organizacao_id)
        REFERENCES local_estoque(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT uq_saldo_estoque_organizacao_produto_local
        UNIQUE (organizacao_id, produto_id, local_estoque_id),
    CONSTRAINT uq_saldo_estoque_identidade_owner
        UNIQUE (id, organizacao_id, produto_id, local_estoque_id),
    CONSTRAINT ck_saldo_estoque_quantidade CHECK (quantidade >= 0),
    CONSTRAINT ck_saldo_estoque_version CHECK (version >= 0)
);

CREATE INDEX ix_saldo_estoque_organizacao_produto
    ON saldo_estoque (organizacao_id, produto_id);
CREATE INDEX ix_saldo_estoque_organizacao_local
    ON saldo_estoque (organizacao_id, local_estoque_id);

CREATE TABLE movimento_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    local_estoque_id BIGINT NOT NULL,
    saldo_estoque_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    delta NUMERIC(15,3) NOT NULL,
    saldo_anterior NUMERIC(15,3) NOT NULL,
    saldo_posterior NUMERIC(15,3) NOT NULL,
    custo_unitario NUMERIC(15,2),
    origem_tipo VARCHAR(50) NOT NULL,
    origem_chave VARCHAR(160) NOT NULL,
    compensado_id BIGINT,
    ator_id BIGINT NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_movimento_estoque_organizacao
        FOREIGN KEY (organizacao_id) REFERENCES organizacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimento_estoque_produto_organizacao
        FOREIGN KEY (organizacao_id, produto_id)
        REFERENCES produto(organizacao_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimento_estoque_local_organizacao
        FOREIGN KEY (local_estoque_id, organizacao_id)
        REFERENCES local_estoque(id, organizacao_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimento_estoque_saldo_owner
        FOREIGN KEY (saldo_estoque_id, organizacao_id, produto_id, local_estoque_id)
        REFERENCES saldo_estoque(id, organizacao_id, produto_id, local_estoque_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_movimento_estoque_ator
        FOREIGN KEY (ator_id) REFERENCES usuario(id) ON DELETE RESTRICT,
    CONSTRAINT uq_movimento_estoque_identidade_owner
        UNIQUE (id, organizacao_id, produto_id, local_estoque_id, saldo_estoque_id),
    CONSTRAINT uq_movimento_estoque_origem
        UNIQUE (organizacao_id, origem_tipo, origem_chave,
                produto_id, local_estoque_id, tipo),
    CONSTRAINT ck_movimento_estoque_tipo CHECK (
        tipo IN ('RECEBIMENTO','BAIXA','AJUSTE','COMPENSACAO')
    ),
    CONSTRAINT ck_movimento_estoque_delta CHECK (delta <> 0),
    CONSTRAINT ck_movimento_estoque_sinal CHECK (
        (tipo = 'RECEBIMENTO' AND delta > 0)
        OR (tipo = 'BAIXA' AND delta < 0)
        OR tipo IN ('AJUSTE','COMPENSACAO')
    ),
    CONSTRAINT ck_movimento_estoque_saldos CHECK (
        saldo_anterior >= 0 AND saldo_posterior >= 0
        AND saldo_posterior = saldo_anterior + delta
    ),
    CONSTRAINT ck_movimento_estoque_custo CHECK (
        custo_unitario IS NULL OR custo_unitario >= 0
    ),
    CONSTRAINT ck_movimento_estoque_origem CHECK (
        length(btrim(origem_tipo)) BETWEEN 1 AND 50
        AND length(btrim(origem_chave)) BETWEEN 1 AND 160
    ),
    CONSTRAINT ck_movimento_estoque_motivo CHECK (
        length(btrim(motivo)) BETWEEN 1 AND 500
    ),
    CONSTRAINT ck_movimento_estoque_compensacao CHECK (
        (tipo = 'COMPENSACAO') = (compensado_id IS NOT NULL)
    )
);

