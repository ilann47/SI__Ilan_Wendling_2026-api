CREATE TABLE baixa_financeira (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT REFERENCES organizacao(id) ON DELETE RESTRICT,
    conta_pagar_id BIGINT REFERENCES conta_pagar(id) ON DELETE RESTRICT,
    conta_receber_id BIGINT REFERENCES conta_receber(id) ON DELETE RESTRICT,
    valor NUMERIC(15,2) NOT NULL CHECK (valor > 0),
    data DATE,
    ator_id BIGINT REFERENCES usuario(id) ON DELETE RESTRICT,
    ator_nome VARCHAR(150),
    chave VARCHAR(160) NOT NULL,
    request_hash VARCHAR(64),
    saldo_anterior BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_baixa_financeira_titulo CHECK (num_nonnulls(conta_pagar_id, conta_receber_id) = 1),
    CONSTRAINT fk_baixa_financeira_pagar_tenant FOREIGN KEY (organizacao_id, conta_pagar_id)
        REFERENCES conta_pagar(organizacao_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_baixa_financeira_receber_tenant FOREIGN KEY (organizacao_id, conta_receber_id)
        REFERENCES conta_receber(organizacao_id,id) ON DELETE RESTRICT,
    CONSTRAINT ck_baixa_financeira_data CHECK (saldo_anterior OR (data IS NOT NULL AND request_hash IS NOT NULL))
);
CREATE UNIQUE INDEX uq_baixa_financeira_pagar_chave ON baixa_financeira(conta_pagar_id,chave)
    WHERE conta_pagar_id IS NOT NULL;
CREATE UNIQUE INDEX uq_baixa_financeira_receber_chave ON baixa_financeira(conta_receber_id,chave)
    WHERE conta_receber_id IS NOT NULL;
CREATE INDEX ix_baixa_financeira_org_data ON baixa_financeira(organizacao_id,created_at,id);

-- Migração do acumulado conhecido, não invenção de pagamentos individuais ou datas.
INSERT INTO baixa_financeira(organizacao_id,conta_pagar_id,valor,data,chave,saldo_anterior)
SELECT organizacao_id,id,valor_pago,data_pagamento,'saldo-anterior-v69',TRUE
FROM conta_pagar WHERE valor_pago > 0;
INSERT INTO baixa_financeira(organizacao_id,conta_receber_id,valor,data,chave,saldo_anterior)
SELECT organizacao_id,id,valor_recebido,data_recebimento,'saldo-anterior-v69',TRUE
FROM conta_receber WHERE valor_recebido > 0;

CREATE FUNCTION proteger_baixa_financeira_v69() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE owner_ref BIGINT;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Historico financeiro e imutavel' USING ERRCODE='23514', CONSTRAINT='ck_baixa_financeira_imutavel';
    END IF;
    IF NEW.conta_pagar_id IS NOT NULL THEN
        SELECT organizacao_id INTO owner_ref FROM conta_pagar WHERE id=NEW.conta_pagar_id;
    ELSE
        SELECT organizacao_id INTO owner_ref FROM conta_receber WHERE id=NEW.conta_receber_id;
    END IF;
    IF NOT FOUND OR owner_ref IS DISTINCT FROM NEW.organizacao_id THEN
        RAISE EXCEPTION 'Owner da baixa diverge do titulo' USING ERRCODE='23503', CONSTRAINT='fk_baixa_financeira_owner';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER tg_baixa_financeira_protegida BEFORE INSERT OR UPDATE OR DELETE ON baixa_financeira
    FOR EACH ROW EXECUTE FUNCTION proteger_baixa_financeira_v69();
