CREATE TABLE registro_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT REFERENCES organizacao(id) ON DELETE RESTRICT,
    acao VARCHAR(100) NOT NULL,
    recurso_tipo VARCHAR(80) NOT NULL,
    recurso_id BIGINT NOT NULL,
    ator_tipo VARCHAR(30) NOT NULL,
    ator_id BIGINT REFERENCES usuario(id) ON DELETE RESTRICT,
    origem VARCHAR(30) NOT NULL,
    evento_id BIGINT,
    patio_id BIGINT,
    dispositivo_id VARCHAR(120),
    ip_origem VARCHAR(45),
    trace_id VARCHAR(100) NOT NULL,
    motivo VARCHAR(500),
    estado_anterior JSONB,
    estado_posterior JSONB,
    versao_anterior BIGINT,
    versao_posterior BIGINT,
    classe_retencao VARCHAR(30) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_auditoria_acao CHECK (acao ~ '^[A-Z][A-Z0-9_]{2,99}$'),
    CONSTRAINT ck_auditoria_recurso CHECK (recurso_tipo ~ '^[A-Z][A-Z0-9_]{2,79}$'),
    CONSTRAINT ck_auditoria_ator CHECK (
        (ator_tipo = 'HUMANO' AND ator_id IS NOT NULL)
        OR (ator_tipo IN ('SISTEMA', 'INTEGRACAO', 'DISPOSITIVO') AND ator_id IS NULL)
    ),
    CONSTRAINT ck_auditoria_origem CHECK (origem IN ('API', 'SISTEMA', 'JOB', 'WEBHOOK', 'OFFLINE')),
    CONSTRAINT ck_auditoria_retencao CHECK (
        classe_retencao IN ('CONFIGURACAO', 'SEGURANCA', 'OPERACIONAL', 'FINANCEIRA', 'FISCAL', 'RH', 'PRIVACIDADE')
    ),
    CONSTRAINT ck_auditoria_estado_anterior CHECK (
        estado_anterior IS NULL OR jsonb_typeof(estado_anterior) = 'object'
    ),
    CONSTRAINT ck_auditoria_estado_posterior CHECK (
        estado_posterior IS NULL OR jsonb_typeof(estado_posterior) = 'object'
    ),
    CONSTRAINT ck_auditoria_versoes CHECK (
        (versao_anterior IS NULL OR versao_anterior >= 0)
        AND (versao_posterior IS NULL OR versao_posterior >= 0)
    )
);

CREATE INDEX ix_auditoria_organizacao_data
    ON registro_auditoria (organizacao_id, ocorrido_em DESC, id DESC);
CREATE INDEX ix_auditoria_recurso
    ON registro_auditoria (recurso_tipo, recurso_id, ocorrido_em DESC);
CREATE INDEX ix_auditoria_ator
    ON registro_auditoria (ator_id, ocorrido_em DESC) WHERE ator_id IS NOT NULL;
CREATE INDEX ix_auditoria_trace ON registro_auditoria (trace_id);

CREATE FUNCTION impedir_mutacao_registro_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'registro_auditoria e append-only' USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER tg_registro_auditoria_append_only
BEFORE UPDATE OR DELETE ON registro_auditoria
FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_registro_auditoria();
