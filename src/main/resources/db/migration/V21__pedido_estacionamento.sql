    ADD CONSTRAINT uq_reserva_id_tenant_ator_evento
        UNIQUE (id, organizacao_id, ator_id, evento_id);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacao_id BIGINT NOT NULL REFERENCES organizacao(id) ON DELETE RESTRICT,
    evento_id BIGINT NOT NULL,
    reserva_inventario_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    numero VARCHAR(40) NOT NULL,
    canal VARCHAR(30) NOT NULL,
    placa_veiculo VARCHAR(7),
    status VARCHAR(30) NOT NULL,
    subtotal NUMERIC(19,2) NOT NULL,
    desconto NUMERIC(19,2) NOT NULL DEFAULT 0,
    taxa NUMERIC(19,2) NOT NULL DEFAULT 0,
    total NUMERIC(19,2) NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL,
    finalizado_em TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_pedido_reserva_tenant_ator_evento
        FOREIGN KEY (reserva_inventario_id, organizacao_id, ator_id, evento_id)
        REFERENCES reserva_inventario (id, organizacao_id, ator_id, evento_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_pedido_reserva UNIQUE (reserva_inventario_id),
    CONSTRAINT uq_pedido_numero UNIQUE (numero),
    CONSTRAINT ck_pedido_numero CHECK (numero ~ '^PED-[A-F0-9]{32}$'),
    CONSTRAINT ck_pedido_canal CHECK (canal ~ '^[A-Z][A-Z0-9_]{0,29}$'),
    CONSTRAINT ck_pedido_placa CHECK (
        placa_veiculo IS NULL OR placa_veiculo ~ '^[A-Z0-9]{7}$'
    ),
    CONSTRAINT ck_pedido_status CHECK (status IN (
        'CRIADO', 'AGUARDANDO_PAGAMENTO', 'CONFIRMADO', 'ATENDIDO',
        'CONCLUIDO', 'EXPIRADO', 'CANCELADO', 'EM_REEMBOLSO',
        'REEMBOLSADO', 'CANCELADO_COM_PENDENCIA'
    )),
    CONSTRAINT ck_pedido_valores CHECK (
        subtotal >= 0 AND desconto >= 0 AND taxa >= 0
        AND total = subtotal - desconto + taxa AND total >= 0
    ),
    CONSTRAINT ck_pedido_moeda CHECK (moeda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_pedido_expiracao CHECK (expira_em > created_at),
    CONSTRAINT ck_pedido_finalizacao CHECK (
        (status IN ('CONCLUIDO', 'EXPIRADO', 'CANCELADO', 'REEMBOLSADO',
                    'CANCELADO_COM_PENDENCIA') AND finalizado_em IS NOT NULL)
        OR (status NOT IN ('CONCLUIDO', 'EXPIRADO', 'CANCELADO', 'REEMBOLSADO',
                           'CANCELADO_COM_PENDENCIA') AND finalizado_em IS NULL)
    ),
    CONSTRAINT ck_pedido_version CHECK (version >= 0)
);

CREATE INDEX ix_pedido_organizacao_evento_status
    ON pedido (organizacao_id, evento_id, status, created_at DESC);
CREATE INDEX ix_pedido_ator
    ON pedido (organizacao_id, ator_id, created_at DESC);
CREATE INDEX ix_pedido_expiracao
    ON pedido (expira_em, id)
    WHERE status IN ('CRIADO', 'AGUARDANDO_PAGAMENTO');

CREATE TABLE comprador_pedido (
    pedido_id BIGINT PRIMARY KEY REFERENCES pedido(id) ON DELETE CASCADE,
    nome VARCHAR(180) NOT NULL,
    email VARCHAR(254) NOT NULL,
    documento VARCHAR(14),
    CONSTRAINT ck_comprador_nome CHECK (length(btrim(nome)) BETWEEN 1 AND 180),
    CONSTRAINT ck_comprador_email CHECK (
        length(btrim(email)) BETWEEN 3 AND 254 AND position('@' IN email) > 1
    ),
    CONSTRAINT ck_comprador_documento CHECK (
        documento IS NULL OR documento ~ '^([0-9]{11}|[0-9]{14})$'
    )
);

CREATE TABLE item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedido(id) ON DELETE RESTRICT,
    produto_id BIGINT NOT NULL,
    alocacao_id BIGINT NOT NULL,
    lote_preco_id BIGINT NOT NULL,
    nome_produto VARCHAR(160) NOT NULL,
    categoria VARCHAR(30) NOT NULL,
    direito VARCHAR(40) NOT NULL,
    inicio_acesso TIMESTAMPTZ NOT NULL,
    fim_acesso TIMESTAMPTZ NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(19,2) NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    total NUMERIC(19,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_item_pedido_produto UNIQUE (pedido_id, produto_id),
    CONSTRAINT ck_item_nome CHECK (length(btrim(nome_produto)) BETWEEN 1 AND 160),
    CONSTRAINT ck_item_categoria CHECK (
        categoria IN ('COMUM', 'VIP', 'PCD', 'STAFF', 'ONIBUS', 'VAN', 'CORTESIA')
    ),
    CONSTRAINT ck_item_direito CHECK (direito IN ('ESTACIONAMENTO_EVENTO')),
    CONSTRAINT ck_item_periodo CHECK (fim_acesso > inicio_acesso),
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco CHECK (
        preco_unitario >= 0 AND total = preco_unitario * quantidade
    ),
    CONSTRAINT ck_item_moeda CHECK (moeda ~ '^[A-Z]{3}$')
);

CREATE INDEX ix_item_pedido_pedido ON item_pedido (pedido_id);

